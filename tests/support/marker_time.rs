//! Test-only live source-kernel authority; never reads committed Native outputs.
#[path = "native_environment.rs"]
mod native_environment;

use std::{path::PathBuf, process::Command};

fn artifacts(keys: &[&str]) -> Option<PathBuf> {
    for key in keys {
        native_environment::binary(key)?;
    }
    match Command::new("node").arg("--version").output() {
        Ok(output) => assert!(output.status.success(), "node --version failed"),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            assert!(
                !native_environment::required(),
                "ARES_REQUIRE_ORCA=1: missing node; Native comparison not executed"
            );
            native_environment::skipped("node is unavailable");
            return None;
        }
        Err(error) => panic!("cannot launch node: {error}"),
    }
    let directory = tempfile::Builder::new()
        .prefix("marker-time-live-")
        .tempdir()
        .unwrap()
        .keep();
    eprintln!("live marker-time artifacts: {directory:?}");
    Some(directory)
}

fn run(directory: &std::path::Path, tool: &str, arguments: &[&std::path::Path]) {
    let repo = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let output = Command::new("node")
        .arg(repo.join("tools/chain-probe").join(tool))
        .args(arguments)
        .output()
        .unwrap();
    std::fs::write(directory.join(format!("{tool}.stdout")), &output.stdout).unwrap();
    std::fs::write(directory.join(format!("{tool}.stderr")), &output.stderr).unwrap();
    assert!(
        output.status.success(),
        "live marker-time {tool} failed: {} (artifacts {directory:?})",
        String::from_utf8_lossy(&output.stderr)
    );
}

pub fn raw_fixture() -> Option<PathBuf> {
    let directory = artifacts(&["ARES_MARKER_TIME_BIN"])?;
    run(&directory, "marker-time-fixtures.mjs", &[&directory]);
    Some(directory)
}

pub fn tagged_directory() -> Option<PathBuf> {
    artifacts(&["ARES_MARKER_TIME_STABLE_BIN"])
}

pub fn tagged_pair(directory: &std::path::Path, input: &str) {
    std::fs::write(directory.join("ares.gcode"), input).unwrap();
    let oracle_input = directory.join("oracle-input.gcode");
    // GCodeProcessor.cpp:2752–2753,3860–3910,5164–5174 (v2.5.0):
    // producer detection selects the embedded configuration before replay.
    const PREFIX: &str = "; generated by Ares ";
    const PRODUCER: &str = concat!("; generated by Ares ", env!("CARGO_PKG_VERSION"));
    let mut banners = input
        .lines()
        .enumerate()
        .filter(|(_, line)| line.starts_with(PREFIX));
    let Some((1, banner)) = banners.next() else {
        panic!("expected an Ares generator line on line 2");
    };
    assert!(banners.next().is_none(), "expected one Ares generator line");
    let timestamp = banner
        .strip_prefix(PRODUCER)
        .and_then(|rest| rest.strip_prefix(" on "))
        .expect("expected the current Ares version and timestamp");
    let shape = b"0000-00-00 at 00:00:00";
    assert!(
        timestamp.len() == shape.len()
            && timestamp.bytes().zip(shape).all(|(byte, &expected)| {
                if expected == b'0' {
                    byte.is_ascii_digit()
                } else {
                    byte == expected
                }
            }),
        "invalid Ares generator timestamp"
    );
    let start = input.find('\n').unwrap() + 1;
    let mut native_input = input.to_owned();
    native_input.replace_range(
        start..start + PRODUCER.len(),
        "; generated by OrcaSlicer 2.5.0",
    );
    std::fs::write(&oracle_input, native_input).unwrap();
    // Stability premise (B16 disposition): the Native producer must be
    // deterministic on the same input — run it twice into separate
    // directories and require byte-identical stable artifacts. The frozen
    // row-count premise this replaces was stale at birth (7478 written by
    // 9b966db3b; the same immutable oracle yields 7475 on that very tree).
    let first = directory.join("stable-first");
    let second = directory.join("stable-second");
    run(&first, "marker-time-stable.mjs", &[&oracle_input, &first]);
    run(&second, "marker-time-stable.mjs", &[&oracle_input, &second]);
    for name in ["stable.tsv", "stable.json", "stable.csv"] {
        let a = std::fs::read(first.join(name)).unwrap();
        let b = std::fs::read(second.join(name)).unwrap();
        assert_eq!(
            a, b,
            "Native marker-time producer is not deterministic on {name}"
        );
    }
    for name in ["stable.tsv", "stable.json", "stable.csv"] {
        std::fs::copy(first.join(name), directory.join(name)).unwrap();
    }
}
