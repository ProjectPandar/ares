#!/usr/bin/env python3
"""Real public E2Es for the explicit parity profile input's fail-closed contract.

Run from an explicitly provisioned Native environment with an external
ARES_PARITY_ARTIFACT_ROOT and valid ARES_PARITY_PROFILE_RESOURCES_DIR.
Only one existing public case runs per negative input; no Native outputs or
expected G-code are generated by this check.
"""
import json
import os
from pathlib import Path
import subprocess
import tempfile

UPSTREAM = '345efec64c7b95a05ce5cf96df0dde66a158835c'
CASE = 'per_object_skirt_support_raft::per_object_skirt_control_matches_native'
REPO = Path(__file__).resolve().parents[3]


def git(*args):
    return subprocess.check_output(['git', *map(str, args)], text=True).strip()


def main():
    assert os.environ.get('ARES_REQUIRE_ORCA') == '1', 'select the required Native environment explicitly'
    resources = Path(os.environ['ARES_PARITY_PROFILE_RESOURCES_DIR']).resolve(strict=True)
    artifacts = Path(os.environ['ARES_PARITY_ARTIFACT_ROOT'])
    assert artifacts.is_absolute() and not artifacts.is_relative_to(REPO), 'artifacts must be external'
    artifacts.mkdir(parents=True, exist_ok=True)
    assert git('-C', resources, 'rev-parse', 'HEAD') == UPSTREAM, 'negative fixture must use the pinned source'
    source = git('-C', resources, 'rev-parse', '--show-toplevel')
    records = []
    with tempfile.TemporaryDirectory(prefix='profile-input-negatives-', dir=artifacts) as temp:
        temp = Path(temp)
        fixture = temp / 'source'
        subprocess.run(['git', 'clone', '--shared', '--no-checkout', source, str(fixture)],
                       check=True, capture_output=True, text=True)
        git('-C', fixture, 'sparse-checkout', 'set', 'resources/profiles')
        git('-C', fixture, 'checkout', '--detach', UPSTREAM)
        profile = fixture / 'resources/profiles/Creality.json'
        profile.write_bytes(profile.read_bytes() + b'\n')
        assert git('-C', fixture, 'rev-parse', 'HEAD') == UPSTREAM
        cases = [
            ('missing', None, 'ARES_PARITY_PROFILE_RESOURCES_DIR is required'),
            ('path', temp / 'does-not-exist', 'invalid ARES_PARITY_PROFILE_RESOURCES_DIR'),
            ('tree', fixture / 'resources', 'profile filesystem tree mismatch'),
        ]
        for label, root, expected in cases:
            env = os.environ.copy()
            env.pop('ARES_PARITY_PROFILE_RESOURCES_DIR', None)
            if root is not None:
                env['ARES_PARITY_PROFILE_RESOURCES_DIR'] = str(root)
            env['CARGO_TERM_COLOR'] = 'never'
            result = subprocess.run([
                'cargo', 'nextest', 'run', '-p', 'ares-cli', '--test', 'orca_parity',
                '-E', f'test({CASE})', '--no-fail-fast', '--test-threads', '1',
            ], cwd=REPO, env=env, capture_output=True, text=True)
            log = result.stdout + result.stderr
            path = artifacts / f'profile-input-{label}.log'
            path.write_text(log)
            passed = result.returncode == 100 and expected in log and 'SKIPPED:' not in log
            records.append({'case':label, 'public_test':CASE, 'exit_code':result.returncode,
                            'expected_panic':expected, 'passed':passed, 'log':str(path),
                            'fixture_head':UPSTREAM if label == 'tree' else None,
                            'fixture_change':'Creality.json raw bytes' if label == 'tree' else None})
            report = {'schema':'ares-profile-input-boundaries-v1', 'records':records,
                      'scope':'input-boundary checks, not strict Native G-code parity'}
            (artifacts / 'profile-input-boundaries.json').write_text(json.dumps(report, indent=2) + '\n')
            assert passed, f'{label}: expected public test panic at profile boundary; see {path}'
            print(f'{label}: PASS (required public panic, no fallback/skip)', flush=True)


if __name__ == '__main__':
    main()
