import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { expect } from "@playwright/test";
import { build, preview } from "vite";
import { test } from "./failureDiagnostics";
import { oraclePath } from "./oracleEnv";

const web = fileURLToPath(new URL("../", import.meta.url));
const repositoryRoot = fileURLToPath(new URL("../../", import.meta.url));
const artifacts = fileURLToPath(new URL("../../target/web-e2e/ksr-project/", import.meta.url));
const fixture = "tests/ksr_fdmtest_v4/ksr_fdmtest_v4.project.3mf";
const source = "the ksr-initialized seed-replay build, see docs/architecture/ard-ksr-initialized-runtime-authority.md";

type Slice = { gcode: string; byteLength: number; identical: boolean };

test("the wasm bindings expose no internal checkpoint hooks", async () => {
  const bindings = await import(new URL("../packages/ares-wasm-js/src/wasm/ares_wasm.js", import.meta.url).href);
  expect(Object.keys(bindings).filter((name) => name.startsWith("task22"))).toEqual([]);
});

test("a project sliced twice through the worker API is complete, repeatable and matches initialized OrcaSlicer 2.5.0-beta ordered bytes", async ({ page }) => {
  test.setTimeout(300_000);
  rmSync(artifacts, { recursive: true, force: true });
  mkdirSync(artifacts, { recursive: true });

  const root = `${web}e2e/ksr-project-page`;
  await build({ root, logLevel: "warn", build: { outDir: `${artifacts}page`, emptyOutDir: true, target: "es2022", chunkSizeWarningLimit: 16_000 } });
  const server = await preview({ root, logLevel: "warn", build: { outDir: `${artifacts}page` }, preview: { host: "127.0.0.1", port: 4179, strictPort: true } });
  let result: Slice;
  try {
    await page.goto("http://127.0.0.1:4179/");
    await expect(page.getByTestId("ready")).toHaveText("ready", { timeout: 60_000 });
    result = await page.evaluate(
      (bytes) => (window as unknown as { aresKsrSlice: (bytes: number[]) => Promise<Slice> }).aresKsrSlice(bytes),
      [...readFileSync(`${repositoryRoot}${fixture}`)],
    );
  } finally {
    // PreviewServer.close destroys open sockets; httpServer.close waits on a browser preconnect forever.
    await server.close();
  }
  const { gcode } = result;
  const capture = `${artifacts}browser.gcode`;
  writeFileSync(capture, gcode);
  const { byteLength, ...shape } = {
    byteLength: result.byteLength,
    identical: result.identical,
    generator: gcode.match(/^; generated by Ares .*$/m)?.[0] ?? null,
    layers: gcode.match(/^; CHANGE_LAYER$/gm)?.length ?? 0,
    hasHeader: gcode.startsWith("; HEADER_BLOCK_START\n"),
    hasFooter: gcode.includes("; EXECUTABLE_BLOCK_END\n\n; filament used [mm] = "),
    hasNonFiniteMotion: /^(?:G[0123]) .*\b(?:NaN|inf|-inf)\b/m.test(gcode),
  };
  writeFileSync(`${artifacts}result.json`, `${JSON.stringify({ byteLength, ...shape }, null, 2)}\n`);
  expect(shape).toEqual({
    identical: true,
    generator: "; generated by Ares 2.5.0",
    layers: 460,
    hasHeader: true,
    hasFooter: true,
    hasNonFiniteMotion: false,
  });
  expect(byteLength).toBeGreaterThan(6_000_000);

  const replay = oraclePath("ARES_KSR_INITIALIZED_BIN", "the KSR initialized seed-replay oracle", source);
  const native = oraclePath("ARES_KSR_INITIALIZED_NATIVE_BIN", "the KSR initialized Native binary", source);
  const resources = oraclePath("ARES_KSR_INITIALIZED_RESOURCES_DIR", "the KSR initialized resources", source);
  if (!replay || !native || !resources) return;

  // Oracle: Print::export_gcode / GCode::do_export of the initialized OrcaSlicer 2.5.0-beta on the same
  // project; the Rust parity test compares the browser capture as ordered bytes.
  const nativeRoot = mkdtempSync(`${tmpdir()}/ares-web-ksr-oracle-`);
  // The replay stays on this run's first allowed CPU instead of producer.rs's re-launch on CPU 0.
  const replayCpu = /^Cpus_allowed_list:\s*(\d+)/m.exec(readFileSync("/proc/self/status", "utf8"))![1];
  console.log(`KSR seeded replay CPU ${replayCpu}`);
  try {
    execFileSync("cargo", ["nextest", "run", "-p", "ares-cli", "--test", "orca_parity", "--test-threads", "2", "-E",
      "test(runner::stock_project_native_stream::browser::browser_output_matches_initialized_orca_ordered_bytes)"], {
      cwd: repositoryRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      env: {
        ...process.env,
        ARES_BROWSER_GCODE: capture,
        ARES_REQUIRE_ORCA: "1",
        ARES_PARITY_ARTIFACT_ROOT: nativeRoot,
        // Byte-equal to producer.rs's repo_root() launcher (CARGO_MANIFEST_DIR/../..), so it runs in-process.
        ARES_ORCA_BIN: `${repositoryRoot}crates/ares-cli/../../scripts/orca-seeded-parity.sh`,
        ARES_ORCA_NATIVE_BIN: native,
        ARES_ORCA_RESOURCES_DIR: resources,
        ORCA_REPLAY_BIN: replay,
        ORCA_REPLAY_SEED: "0",
        ORCA_REPLAY_CPU: replayCpu,
      },
    });
  } catch (error) {
    const { stdout, stderr } = error as { stdout: string; stderr: string };
    throw new Error(`initialized OrcaSlicer 2.5.0-beta ordered bytes differ from ${capture} (Native artifacts ${nativeRoot})\n${stdout}\n${stderr}`, { cause: error });
  }
  expect(readdirSync(nativeRoot).filter((name) => name.startsWith("ksr-initialized-dispatch-"))).toEqual([]);
});
