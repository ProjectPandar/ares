import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { expect } from "@playwright/test";
import type { RangeMove } from "./colorRanges";
import { aresGeneratorLine } from "./orcaGcode";

export type Move = RangeMove & { gcodeId: number; x: number; y: number; z: number; internalOnly: boolean; extruder: number; deltaE: number };
const f32 = Math.fround;

/**
 * Upstream GCodeProcessor moves of the browser's G-code, from the procgcode oracle
 * (`tools/chain-probe/procgcode.nix`, `--dump-moves`). Only used for expected values.
 */
export function oracleMoves(oracle: string, gcodePath: string, workDir: string): Move[] {
  // `GCodeProcessor::detect_producer` only parses HEIGHT/WIDTH tags for known
  // producers; renaming keeps every line id.
  const input = `${workDir}oracle-input.gcode`;
  const gcode = readFileSync(gcodePath, "utf8");
  expect(gcode.match(/^; generated by Ares .*$/gm), "one exact Ares generator line").toEqual([aresGeneratorLine]);
  writeFileSync(input, gcode.replace(`\n${aresGeneratorLine}\n`, "\n; generated by OrcaSlicer 2.5.0\n"));
  const csv = `${workDir}oracle-moves.csv`;
  execFileSync(oracle, ["--process-gcode", input, "--dump-moves", csv], { stdio: "ignore" });
  const [header, ...rows] = readFileSync(csv, "utf8").trimEnd().split("\n");
  const column = Object.fromEntries(header.split(",").map((name, index) => [name, index]));
  const parsed = rows.map((row) => row.split(",").map(Number));
  const dynamics = oracleDynamics(input, workDir, parsed.map((values) => ({ gcode_id: values[column.gcode_id], type: values[column.type] })));
  return parsed.map((values, index) => {
    return {
      gcodeId: values[column.gcode_id],
      type: values[column.type],
      role: values[column.role],
      internalOnly: values[column.internal_only] === 1,
      extruder: values[column.extruder_id],
      deltaE: values[column.delta_extruder],
      x: values[column.x],
      y: values[column.y],
      z: values[column.z],
      layer: values[column.layer_id],
      width: values[column.width],
      height: values[column.height],
      feedrate: values[column.feedrate],
      mm3PerMm: values[column.mm3_per_mm],
      fanSpeed: values[column.fan_speed],
      temperature: values[column.temperature],
      time: values[column.time0],
      ...dynamics[index],
    };
  });
}

/**
 * ORCA `MoveVertex` pressure advance / acceleration / jerk (`store_move_vertex`,
 * `GCodeProcessor.cpp:5630-5664`) and Normal-mode `actual_feedrate`
 * (`TimeMachine::calculate_time`, `:480-572`, `:5962-5997`) per move, from the initialized-native dynamics
 * oracle (`tools/chain-probe/procgcode-dynamics.nix`, `--dump-move-dynamics`).
 */
function oracleDynamics(input: string, workDir: string, moves: { gcode_id: number; type: number }[]) {
  const oracle = process.env.ARES_PROCGCODE_DYNAMICS_BIN;
  if (!oracle) throw new Error("ARES_PROCGCODE_DYNAMICS_BIN is required for the motion attributes oracle");
  const csv = `${workDir}oracle-dynamics.csv`;
  execFileSync(oracle, ["--process-gcode", input, "--dump-move-dynamics", csv], { stdio: "ignore" });
  const [header, ...rows] = readFileSync(csv, "utf8").trimEnd().split("\n");
  expect(header).toBe("gcode_id,type,internal_only,pressure_advance,acceleration,jerk,actual_feedrate");
  expect(rows).toHaveLength(moves.length);
  return rows.map((row, index) => {
    const [gcodeId, type, , pressureAdvance, acceleration, jerk, actualFeedrate] = row.split(",").map(Number);
    expect([gcodeId, type], `dynamics row ${index}`).toEqual([moves[index].gcode_id, moves[index].type]);
    return { pressureAdvance: f32(pressureAdvance), acceleration: f32(acceleration), jerk: f32(jerk), actualFeedrate: f32(actualFeedrate) };
  });
}
