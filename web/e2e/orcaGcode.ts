import { expect } from "@playwright/test";

/**
 * `normalize_one_generator_line` (crates/ares-cli/tests/stock_project_whole_file/golden.rs): exactly one
 * slicer generator line, plus any vendor start G-code timestamp lines, are host identity.
 */
export function normalize(gcode: string, slicer: "OrcaSlicer" | "Ares") {
  const canonical = slicer === "OrcaSlicer"
    ? /^; generated by OrcaSlicer 2\.5\.0 on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}$/gm
    : /^; generated by Ares 2\.5\.0$/gm;
  expect(gcode.match(canonical), `one ${slicer} generator line`).toHaveLength(1);
  return gcode
    .replace(canonical, "; generated by <SLICER> 2.5.0")
    .replace(/^(; generated by .+) on \d{4}-\d{1,2}-\d{1,2} at \d{1,2}:\d{1,2}:\d{1,2}$/gm, "$1 on <DATE> at <TIME>");
}
