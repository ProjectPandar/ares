import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

/**
 * Upstream preview data for the E2E: runs the GCodeProcessor oracle
 * (`tools/chain-probe/procgcode.nix`, `--dump-moves`) on Ares G-code and
 * builds libvgcode `GCodeInputData` the way `LibVGCodeWrapper.cpp convert()`
 * (`:191-268`) and `Layers::update` (`libvgcode/src/Layers.cpp:20`) do.
 * Plain arrays, so the result crosses `page.evaluate`.
 */
export interface OracleToolpaths {
  vertexCount: number;
  positions: number[];
  widths: number[];
  heights: number[];
  feedrates: number[];
  fanSpeeds: number[];
  temperatures: number[];
  times: number[];
  roles: number[];
  moveTypes: number[];
  extruderIds: number[];
  colorIds: number[];
  layerIds: number[];
  layerZs: number[];
  layerRanges: number[];
}

/** libslic3r `ExtrusionRole` index -> libvgcode `EGCodeExtrusionRole` index (`LibVGCodeWrapper.cpp:99`). */
const ROLE_TO_VGCODE = [0, 1, 2, 3, 4, 5, 6, 15, 7, 8, 16, 9, 10, 17, 11, 12, 18, 13, 14, 19];
const VG_EXTRUDE = 10;
const VG_CUSTOM_ROLE = 14;
/** `move_type_to_option` returns `EOptionType::COUNT` / Travels / Wipes for these. */
const PHANTOM_TYPES = new Set([0, 8, 9, 10]);

type Move = Record<"gcode_id" | "type" | "role" | "extruder_id" | "cp_color_id" | "x" | "y" | "z" | "feedrate"
  | "width" | "height" | "mm3_per_mm" | "fan_speed" | "temperature" | "time0" | "layer_id", number>;

export function oracleToolpaths(oracle: string, gcodePath: string, workDir: string): OracleToolpaths {
  // `GCodeProcessor::detect_producer` only parses HEIGHT/WIDTH tags for known
  // producers; renaming keeps every line id.
  const input = `${workDir}oracle-input.gcode`;
  const renamed = readFileSync(gcodePath, "utf8").replace("\n; generated by Ares 2.4.2\n", "\n; generated by OrcaSlicer 2.4.2\n");
  writeFileSync(input, renamed);
  const csv = `${workDir}oracle-moves.csv`;
  execFileSync(oracle, ["--process-gcode", input, "--dump-moves", csv], { stdio: "ignore" });
  const [header, ...rows] = readFileSync(csv, "utf8").trimEnd().split("\n");
  const names = header.split(",");
  const moves = rows.map((row) => {
    const values = row.split(",").map(Number);
    return Object.fromEntries(names.map((name, index) => [name, values[index]])) as Move;
  });
  return convert(moves);
}

function convert(moves: Move[]): OracleToolpaths {
  const out: OracleToolpaths = {
    vertexCount: 0, positions: [], widths: [], heights: [], feedrates: [], fanSpeeds: [], temperatures: [], times: [],
    roles: [], moveTypes: [], extruderIds: [], colorIds: [], layerIds: [], layerZs: [], layerRanges: [],
  };
  const push = (curr: Move, at: Move, time: number) => {
    const id = out.vertexCount++;
    const role = ROLE_TO_VGCODE[curr.role];
    out.positions.push(at.x, at.y, at.z);
    out.widths.push(curr.width);
    out.heights.push(curr.height);
    out.feedrates.push(curr.feedrate);
    out.fanSpeeds.push(curr.fan_speed);
    out.temperatures.push(curr.temperature);
    out.times.push(time);
    out.roles.push(role);
    out.moveTypes.push(curr.type);
    out.extruderIds.push(curr.extruder_id);
    out.colorIds.push(curr.cp_color_id);
    out.layerIds.push(curr.layer_id);
    // Layers::update
    const extrudeZ = curr.type === VG_EXTRUDE && role !== VG_CUSTOM_ROLE;
    if (curr.layer_id === out.layerZs.length) {
      out.layerZs.push(extrudeZ ? at.z : 0);
      out.layerRanges.push(id, id);
    } else {
      if (extrudeZ) out.layerZs[out.layerZs.length - 1] = at.z;
      out.layerRanges[out.layerRanges.length - 1] = id;
    }
  };
  for (let i = 1; i < moves.length; i++) {
    const [prev, curr] = [moves[i - 1], moves[i]];
    const pathStart = out.vertexCount === 0 || prev.type !== curr.type || prev.role !== curr.role
      || prev.mm3_per_mm !== curr.mm3_per_mm;
    if (PHANTOM_TYPES.has(curr.type) && pathStart) push(curr, prev, 0);
    push(curr, curr, curr.time0);
  }
  return out;
}
