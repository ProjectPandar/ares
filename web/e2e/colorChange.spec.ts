import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { expect, type Page } from "@playwright/test";
import { test } from "./failureDiagnostics";
import { normalize } from "./orcaGcode";
import { oraclePath } from "./oracleEnv";
import { canvasDigest } from "./toolpathPreview";

const root = fileURLToPath(new URL("../../", import.meta.url));
const artifacts = `${root}target/web-e2e/color-change`;
const seconds = (value: number) => `${Math.round(value)} s`;

async function slice(page: Page, project: string) {
  await page.getByRole("link", { name: "Prepare", exact: true }).click();
  await page.getByTestId("import-input").setInputFiles(project);
  await expect(page.getByTestId("status")).toHaveText("Ready to slice");
  await page.getByRole("button", { name: "Slice plate", exact: true }).click();
  await expect(page.getByTestId("status")).toContainText("Slice complete", { timeout: 240_000 });
  await page.getByRole("link", { name: "Preview", exact: true }).click();
  await expect(page.getByTestId("toolpaths-pending")).toHaveCount(0);
  await page.getByTestId("view-type").selectOption("ColorPrint");
}

// Display expectations use the raw upstream processor, not an Ares snapshot.
// Geometry identity is separately locked against raw + stable-index diagnostic
// in processed_color_change/native.rs; G-code/M73 use the unmodified slicer.
test("ColorChange shows source records, unavailable usage, view restoration and clean reload", async ({ page }) => {
  test.setTimeout(240_000);
  const official = oraclePath("ORCA_APPDIR", "the unmodified slicing oracle", "official OrcaSlicer 2.4.2 AppImage");
  const oracle = oraclePath("ARES_PROCGCODE_BIN", "raw ColorChange processor", "tools/chain-probe/procgcode.nix");
  if (!official || !oracle) test.skip();
  mkdirSync(artifacts, { recursive: true });
  execFileSync(process.execPath, [`${root}web/e2e/colorChangeOracle.mjs`, artifacts], { cwd: root });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.locator(".engine-dot.ready")).toBeVisible({ timeout: 30_000 });
  for (const name of ["normal", "stop-times", "zero-before"]) {
    const directory = `${artifacts}/${name}`;
    await slice(page, `${directory}/project.3mf`);
    const changes = page.getByTestId("color-print-details");
    await expect(changes).toBeVisible();
    const [download] = await Promise.all([page.waitForEvent("download"), page.getByRole("button", { name: "Export G-code" }).click()]);
    const path = `${directory}/browser.gcode`;
    await download.saveAs(path);
    const gcode = readFileSync(path, "utf8");
    const nativeGcode = readFileSync(`${directory}/plate_1.gcode`, "utf8");
    expect(normalize(gcode, "Ares")).toBe(normalize(nativeGcode, "OrcaSlicer"));
    const m73 = (text: string) => text.split("\n").filter((line) => line.startsWith("M73 ")).join("\n");
    expect(m73(gcode).length).toBeGreaterThan(0);
    expect(m73(gcode)).toBe(m73(nativeGcode));
    writeFileSync(`${directory}/gcode.sha256`, createHash("sha256").update(gcode).digest("hex"));
    const oracleInput = `${directory}/oracle-input.gcode`;
    writeFileSync(oracleInput, gcode.replace("; generated by Ares 2.4.2", "; generated by OrcaSlicer 2.4.2"));
    writeFileSync(`${directory}/raw-native.log`, execFileSync(oracle!, ["--process-gcode", oracleInput, "--dump-color-change", `${directory}/raw-native.json`, "--dump-moves", `${directory}/raw-native.csv`]));
    const native = JSON.parse(readFileSync(`${directory}/raw-native.json`, "utf8")) as {
      volumes_per_color_change: number[]; filament_diameters: number[]; filament_densities: number[];
      custom_gcode_times: { duration: number; remaining: number }[];
      custom_gcode_per_print_z: { print_z: number; type: number }[];
    };
    if (name === "zero-before") {
      expect(native.volumes_per_color_change).toHaveLength(1);
      expect(native.custom_gcode_times).toHaveLength(2);
      await expect(changes).toContainText("Partial usage unavailable");
      await expect(changes.getByRole("table", { name: "Partial print records" })).toHaveCount(0);
      await expect(changes.locator(".printed-colors li")).toHaveCount(1);
    } else {
      expect(native.volumes_per_color_change).toHaveLength(3);
      expect(native.custom_gcode_times).toHaveLength(4);
      const rows = changes.getByRole("table", { name: "Partial print records" }).locator("tbody tr");
      await expect(rows).toHaveCount(7);
      expect(await rows.locator("th").allTextContents()).toEqual(["Print", "Color change", "Print", "Pause", "Print", "Color change", "Print"]);
      for (const [row, timeIndex, volumeIndex] of [[0, 0, 0], [2, 1, -1], [4, 2, 1], [6, 3, 2]]) {
        const time = native.custom_gcode_times[timeIndex];
        const cells = rows.nth(row).locator("td");
        await expect(cells.nth(0)).toHaveText(seconds(time.remaining));
        await expect(cells.nth(1)).toHaveText(seconds(time.duration));
        if (volumeIndex < 0) await expect(cells.nth(2)).toHaveText("—");
        else {
          const volume = native.volumes_per_color_change[volumeIndex];
          const m = 0.001 * volume / (Math.PI * (0.5 * native.filament_diameters[0]) ** 2);
          const g = volume * native.filament_densities[0] * 0.001;
          await expect(cells.nth(2)).toHaveText(`${m.toFixed(2)} m · ${g.toFixed(2)}g`);
        }
      }
      await expect(changes.locator(".printed-colors li")).toHaveCount(3);
      await expect(changes.locator(".printed-colors li").nth(1).locator(".legend-swatch")).toHaveCSS("background-color", "rgb(255, 48, 48)");
      await expect(changes.locator(".printed-colors li").nth(2).locator(".legend-swatch")).toHaveCSS("background-color", "rgb(48, 48, 255)");
      const ranges = changes.locator(".color-change-ranges li");
      await expect(ranges).toHaveCount(2);
      for (const [i, item] of native.custom_gcode_per_print_z.filter((record) => record.type === 0).entries()) {
        await expect(ranges.nth(i)).toContainText(item.print_z.toFixed(2));
        await expect(ranges.nth(i)).toContainText("mm");
      }
      await page.screenshot({ path: `${directory}/records.png` });
      const legendBox = (await page.getByTestId("legend").boundingBox())!;
      const sliderBox = (await page.getByTestId("moves-slider").boundingBox())!;
      expect(legendBox.y + legendBox.height, "all source records remain above the moves slider").toBeLessThanOrEqual(sliderBox.y - 4);
      const colorView = await canvasDigest(page);
      for (const view of ["FeatureType", "Speed"]) {
        await page.getByTestId("view-type").selectOption(view);
        await expect(changes).toHaveCount(0);
        await page.getByTestId("view-type").selectOption("ColorPrint");
        await expect(changes).toBeVisible();
        expect(await canvasDigest(page)).toBe(colorView);
      }
    }
    await page.screenshot({ path: `${directory}/preview.png` });
  }
  await slice(page, `${root}tests/parity/orca_cli_ender3.3mf`);
  await expect(page.getByTestId("color-print-details")).toHaveCount(0);
  await expect(page.getByTestId("filament-legend")).toBeVisible();
  await page.screenshot({ path: `${artifacts}/reload.png` });
  expect(errors).toEqual([]);
});
