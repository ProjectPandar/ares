import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { expect } from "@playwright/test";
import { test } from "./failureDiagnostics";
import { orcaPlate } from "./platerOracle";
import { systemPresetCatalog } from "./systemPresetCatalog";

const ramp = new URL("../../tests/parity/organic-branch-circle/ramp.3mf", import.meta.url);

function withoutGenerator(file: string) {
  // Latin-1 decoding preserves every byte, including line endings.
  const gcode = readFileSync(file, "latin1");
  const banner = /^; generated by OrcaSlicer (?:2\.5\.0|Ares-\S+) on [^\r\n]+\r?\n/gm;
  expect(gcode.match(banner), "one slicer generator line").toHaveLength(1);
  return gcode.replace(banner, "");
}

test("organic ramp support extrusion matches OrcaSlicer in the browser", async ({ page }, info) => {
  mkdirSync(info.outputDir, { recursive: true });
  const project = info.outputPath("ramp.3mf");
  copyFileSync(ramp, project);
  const lane = process.env.ARES_PARITY_SEEDED_REFERENCE === "1" ? "seeded" : "official";
  const native = orcaPlate(project, 1, lane);
  test.skip(native === null, "OrcaSlicer is unavailable");
  // Compare the raw reference artifact rather than the shared helper's normalization.
  const expected = withoutGenerator(info.outputPath(`ramp-plate_1-${lane}.gcode`));
  const support = expected.split(/^;(?: FEATURE: |TYPE:)Support\r?$/m).slice(1);
  expect(support.some((section) => /^G1 [^\r\n]* E(?:[1-9]\d*(?:\.\d+)?|0?\.\d*[1-9]\d*)(?:\s|$)/m.test(
    section.split(/^;(?: FEATURE: |TYPE:)/m, 1)[0],
  )), "Native extrudes the ramp's support").toBe(true);

  const catalogPath = process.env.ARES_PARITY_PROJECT_PRESET_CATALOG;
  const catalog = catalogPath ? readFileSync(catalogPath, "utf8") : await systemPresetCatalog();
  const origin = "http://slicer.test";
  const pkg = new URL("../packages/ares-wasm-js/src/wasm/", import.meta.url);
  await page.route(`${origin}/`, (route) => route.fulfill({ contentType: "text/html", body: "<!doctype html>" }));
  for (const [name, path, contentType] of [
    ["ares_wasm.js", fileURLToPath(new URL("ares_wasm.js", pkg)), "text/javascript"],
    ["ares_wasm_bg.wasm", fileURLToPath(new URL("ares_wasm_bg.wasm", pkg)), "application/wasm"],
    ["ramp.3mf", project, "application/octet-stream"],
  ]) {
    await page.route(`${origin}/${name}`, (route) => route.fulfill({ path, contentType }));
  }
  await page.route(`${origin}/catalog.json`, (route) => route.fulfill({ contentType: "application/json", body: catalog }));
  await page.goto(origin);
  const bytes = await page.evaluate(async (modulePath) => {
    const wasm: typeof import("../packages/ares-wasm-js/src/wasm/ares_wasm") = await import(modulePath);
    await wasm.default({ module_or_path: "/ares_wasm_bg.wasm" });
    const [input, catalog] = await Promise.all([
      fetch("/ramp.3mf").then((response) => response.arrayBuffer()),
      fetch("/catalog.json").then((response) => response.text()),
    ]);
    return Array.from(await wasm.sliceProjectPlateWithCatalog(new Uint8Array(input), undefined, undefined, catalog));
  }, "/ares_wasm.js");
  const output = info.outputPath("browser.gcode");
  writeFileSync(output, Buffer.from(bytes));
  const actual = withoutGenerator(output);
  if (actual !== expected) {
    const a = actual.split("\n");
    const b = expected.split("\n");
    const first = (a.length >= b.length ? a : b).findIndex((_, i) => a[i] !== b[i]);
    expect(a[first], `whole G-code, first differing line ${first + 1}`).toBe(b[first]);
  }
});
