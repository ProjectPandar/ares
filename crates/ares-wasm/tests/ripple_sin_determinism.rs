use ares_wasm::slice_project_plate_processed_with_catalog_bytes;

fn strip_generator_line(gcode: &str) -> String {
    let mut removed = 0usize;
    let mut out = String::with_capacity(gcode.len());
    for line in gcode.split_inclusive('\n') {
        if line.starts_with("; generated by OrcaSlicer ") {
            removed += 1;
            continue;
        }
        out.push_str(line);
    }
    assert_eq!(removed, 1, "expected exactly one generator header line");
    out
}

#[tokio::test]
async fn ripple_sin_witness_matches_core_and_emits_correctly_rounded_moves() {
    let project = include_bytes!(
        "../../../tests/parity/fuzzy_skin_supported_area/classic_ripple_sin_witness.3mf"
    );
    let mut wasm_out =
        slice_project_plate_processed_with_catalog_bytes(project.to_vec(), Some(1), None, None)
            .await
            .expect("wasm entry point slices ripple sine witness");
    let wasm_gcode = String::from_utf8(wasm_out.take_gcode()).unwrap();

    let core_bytes = ares_core::slice_project_plate_validated(
        project,
        ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
        Some(1),
        &ares_core::ConfigOverrides::default(),
        ares_core::SlicerContext::new(0),
    )
    .await
    .expect("core slices ripple sine witness");
    let core_gcode = String::from_utf8(core_bytes).unwrap();

    assert_eq!(
        strip_generator_line(&wasm_gcode),
        strip_generator_line(&core_gcode),
        "wasm entry point output must match core output byte-for-byte"
    );
    for expected in [
        "G1 X100.25 Y129.249 E.02001\n",
        "G1 X100.25 Y129.249 E.02\n",
    ] {
        assert!(
            wasm_gcode.contains(expected),
            "expected correctly rounded ripple move {expected:?}"
        );
    }

    let directory = std::path::Path::new(env!("CARGO_TARGET_TMPDIR")).join("ripple-sin-witness");
    std::fs::create_dir_all(&directory).unwrap();
    std::fs::write(directory.join("wasm.gcode"), &wasm_gcode).unwrap();
    std::fs::write(directory.join("core.gcode"), &core_gcode).unwrap();
}
