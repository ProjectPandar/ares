import init, * as bindings from "/target/wasm-browser/ares_wasm.js";

const decoder = new TextDecoder();

async function fixtureBytes() {
  const response = await fetch("/tests/ksr_fdmtest_v4/ksr_fdmtest_v4.project.3mf");
  if (!response.ok) throw new Error(`fixture fetch failed: ${response.status}`);
  return new Uint8Array(await response.arrayBuffer());
}

export async function startProjectSlicePage() {
  await init();
  window.sliceFixtureProject = async () => {
    const output = await bindings.sliceProject(await fixtureBytes());
    const text = decoder.decode(output);
    const generator = text.match(/^; generated by Ares 2\.4\.2 on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}$/m);
    return {
      gcode: text,
      byteLength: output.length,
      generator: generator?.[0] ?? null,
      layers: text.match(/^; CHANGE_LAYER$/gm)?.length ?? 0,
      hasHeader: text.startsWith("; HEADER_BLOCK_START\n"),
      hasFooter: text.includes("; EXECUTABLE_BLOCK_END\n\n; filament used [mm] = "),
      hasNonFiniteMotion: /^(?:G[0123]) .*\b(?:NaN|inf|-inf)\b/m.test(text),
    };
  };
  window.bindingExports = Object.keys(bindings).sort();
  window.aresReady = true;
}
