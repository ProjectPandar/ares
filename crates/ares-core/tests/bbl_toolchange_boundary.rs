//! BBL toolchange boundary: the object-end unique-label marker (M625) flushes
//! in the layer tail block (`GCode.cpp:5544`), between the eager lift and
//! `set_extruder`'s toolchange top-up retract (`GCode.cpp:7754`), and the
//! first travel after the toolchange keeps the hop as a two-segment
//! `G1 X Y Z(hop)` + `G1 Z(layer)` move (`travel_to_xyz`,
//! `GCodeWriter.cpp:685-710`).
//!
//! The fixture keeps the X2D machine's full custom-gcode chain except
//! `change_filament_gcode`, which is the legal user template
//! `T[next_extruder]`: main's placeholder parser does not yet carry the
//! flush-placeholder family (`L[flush_length]`, `flush_temperatures`, …)
//! that the machine's stock template references, and the strict template
//! validation rejects it. The retraction machinery under test is
//! independent of the template body. Once the flush-placeholder chain
//! lands, a second case on the stock template should be added
//! (see clusters.md).

use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};

fn fixture(name: &str) -> Vec<u8> {
    std::fs::read(format!(
        "{}/../../tests/parity/validation/{name}",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap()
}

fn normalize(text: &str) -> Vec<&str> {
    fn normalize_line(line: &str) -> &str {
        if line.starts_with("; generated by") {
            "; generated by"
        } else {
            line
        }
    }
    text.lines().map(normalize_line).collect()
}

#[tokio::test]
async fn bbl_toolchange_boundary_matches_native() {
    let gcode = slice_project_plate(
        fixture("bbl-toolchange-boundary.3mf"),
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    let gcode_text = String::from_utf8(gcode.to_vec()).unwrap();
    let actual = normalize(&gcode_text);
    let expected_text =
        String::from_utf8(fixture("bbl-toolchange-boundary-expected.gcode")).unwrap();
    let expected = normalize(&expected_text);
    for (index, (actual, expected)) in actual.iter().zip(&expected).enumerate() {
        assert_eq!(actual, expected, "first mismatch at line {}", index + 1);
    }
    assert_eq!(actual.len(), expected.len());
}
