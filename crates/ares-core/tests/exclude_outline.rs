//! EXCLUDE_OBJECT_DEFINE hull polygon: upstream projects the 3D convex-hull
//! mesh through the instance transform WITHOUT its translation
//! (`get_matrix_no_offset`, Model.cpp:2625-2644), scales with the C-cast
//! truncating `scaled()` (Point.hpp:665-670 — the rounding variant is
//! commented out), then translates the polygon by the truncated scaled
//! offset. A ~90° instance transform carries 2.22044605e-16 residues whose
//! negative rotated coordinates truncate +1 scaled unit, breaking the exact
//! collinearity of the dumbbell mesh's edge midpoints; the monotone-chain
//! hull (Geometry/ConvexHull.cpp:12-40) then keeps one midpoint per vertical
//! edge. An identity transform has no residue: both engines emit the plain
//! 4-corner rectangle (the control).

use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};

fn fixture(name: &str) -> Vec<u8> {
    std::fs::read(format!(
        "{}/../../tests/parity/validation/{name}",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap()
}

fn normalize(text: &str) -> Vec<&str> {
    fn normalize_line(line: &str) -> &str {
        if line.starts_with("; generated by") {
            "; generated by"
        } else {
            line
        }
    }
    text.lines().map(normalize_line).collect()
}

fn assert_matches_native(actual: &[u8], expected_name: &str) {
    let actual = String::from_utf8(actual.to_vec()).unwrap();
    let expected = String::from_utf8(fixture(expected_name)).unwrap();
    let actual_lines = normalize(&actual);
    let expected_lines = normalize(&expected);
    for (index, (actual, expected)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        assert_eq!(actual, expected, "first mismatch at line {}", index + 1);
    }
    assert_eq!(actual_lines.len(), expected_lines.len());
}

#[tokio::test]
async fn rotation_residue_hull_keeps_edge_midpoints_like_native() {
    let gcode = slice_project_plate(
        fixture("exclude-outline-jitter.3mf"),
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    // The native POLYGON keeps one midpoint per vertical edge
    // ([[208,195],[218,195],[218,215],[218,225],[208,225],[208,205]]);
    // current Ares emits the 4-corner bbox.
    assert_matches_native(&gcode, "exclude-outline-jitter-expected.gcode");
}

#[tokio::test]
async fn identity_transform_hull_stays_four_corners() {
    let gcode = slice_project_plate(
        fixture("exclude-outline-identity.3mf"),
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    assert_matches_native(&gcode, "exclude-outline-identity-expected.gcode");
}
