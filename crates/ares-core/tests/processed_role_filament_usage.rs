#[test]
fn required_native_role_map_cannot_fall_back_to_frozen_capture() {
    native_policy_checks::require_missing_dependencies_fail(
        "native_role_map_is_bound_to_same_run_footer",
        &["ARES_ROLE_ORACLE_LIVE", "ARES_GDB_BIN"],
    );
}

const PROJECT: &[u8] = include_bytes!("../../../tests/parity/validation/kobra3-centered/0.8.3mf");
const NATIVE: &[u8] = include_bytes!("../../../tests/parity/role-filament-usage/native.gcode");
const MAP: &[u8] = include_bytes!("../../../tests/parity/role-filament-usage/native-map.json");

fn sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn generator_only(bytes: &[u8]) -> String {
    std::str::from_utf8(bytes)
        .unwrap()
        .split_inclusive('\n')
        .map(|line| {
            if line.starts_with("; generated by ") {
                "; generated by <SLICER>\n"
            } else {
                line
            }
        })
        .collect()
}

fn footer(bytes: &[u8], unit: &str) -> String {
    let prefix = format!("; filament used [{unit}] = ");
    let values: Vec<_> = std::str::from_utf8(bytes)
        .unwrap()
        .lines()
        .filter_map(|line| line.strip_prefix(&prefix))
        .collect();
    assert_eq!(values.len(), 1);
    values[0].to_owned()
}

fn native_map() -> Value {
    let record: Value = serde_json::from_slice(MAP).unwrap();
    assert_eq!(record["input_sha256"], sha256(PROJECT));
    assert_eq!(record["gcode_sha256"], sha256(NATIVE));
    assert_eq!(record["footer_check"]["passed"], true);
    let rows = record["roles"].as_array().unwrap();
    assert_eq!(rows.len(), 8, "the real project exercises eight roles");
    let mut meters = 0.0;
    let mut grams = 0.0;
    for row in rows {
        meters += f64::from_bits(row["bits"][0].as_u64().unwrap());
        grams += f64::from_bits(row["bits"][1].as_u64().unwrap());
    }
    assert_eq!(format!("{:.2}", meters * 1000.0), footer(NATIVE, "mm"));
    assert_eq!(format!("{grams:.2}"), footer(NATIVE, "g"));
    record
}

#[test]
fn native_role_map_is_bound_to_same_run_footer() {
    let frozen = native_map();
    if std::env::var_os("ARES_ROLE_ORACLE_LIVE").is_some() {
        let repo = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        let stamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let output = repo.join(format!("target/role-filament-usage/native-live-{stamp}"));
        let run = std::process::Command::new("nix")
            .args(["shell", "nixpkgs#gdb", "-c", "gdb", "-nx", "-batch", "-x"])
            .arg(repo.join("tools/chain-probe/role-filament-map.py"))
            .env(
                "ARES_ROLE_ORACLE_INPUT",
                repo.join("tests/parity/validation/kobra3-centered/0.8.3mf"),
            )
            .env("ARES_ROLE_ORACLE_OUTPUT", &output)
            .output()
            .unwrap();
        std::fs::write(
            output.join("native.log"),
            [&run.stdout[..], &run.stderr[..]].concat(),
        )
        .unwrap();
        assert!(run.status.success());
        let live: Value =
            serde_json::from_slice(&std::fs::read(output.join("role-map.json")).unwrap()).unwrap();
        assert_eq!(live["roles"], frozen["roles"]);
        assert_eq!(live["footer_check"], frozen["footer_check"]);
        let gcode = std::fs::read(output.join("plate_1.gcode")).unwrap();
        assert_eq!(live["gcode_sha256"], sha256(&gcode));
        assert!(generator_only(&gcode) == generator_only(NATIVE));
    }
}

#[tokio::test]
async fn processed_role_filament_usage_matches_native_map() {
    // The reference is the live Native map captured during the SAME slice
    // that wrote native.gcode, after process_caches and before stats export.
    let native = native_map();
    let output = slice_project_plate_processed(
        PROJECT.to_vec(),
        GenerationMetadata::default(),
        Some(1),
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    let expected = generator_only(NATIVE);
    let actual = generator_only(&output.gcode);
    let first = actual
        .split_inclusive('\n')
        .zip(expected.split_inclusive('\n'))
        .position(|(actual, expected)| actual != expected);
    assert!(
        actual == expected,
        "whole G-code control differs: first common-range line={first:?}, bytes={}/{}",
        actual.len(),
        expected.len()
    );
    let root = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../target/role-filament-usage");
    std::fs::create_dir_all(&root).unwrap();
    std::fs::write(root.join("ares.gcode"), &output.gcode).unwrap();
    let statistics = serde_json::to_value(&output.result.print_statistics).unwrap();
    std::fs::write(
        root.join("ares-statistics.json"),
        serde_json::to_vec_pretty(&statistics).unwrap(),
    )
    .unwrap();
    let roles = statistics["used_filaments_per_role"]
        .as_object()
        .expect("Native has eight nonzero roles; Ares must export the role map");
    let rows = native["roles"].as_array().unwrap();
    assert_eq!(roles.len(), rows.len(), "complete Native role key set");
    for row in rows {
        let role = row["role"].as_str().unwrap();
        let values = roles[role].as_array().unwrap();
        assert_eq!(values.len(), 2);
        for (index, value) in values.iter().enumerate() {
            assert_eq!(
                value.as_f64().unwrap().to_bits(),
                row["bits"][index].as_u64().unwrap(),
                "{role}, pair index {index} (meters, grams)"
            );
        }
    }
}
