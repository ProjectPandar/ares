#[tokio::test]
async fn byte_input_output_uses_the_final_release_generator_identity() {
    let input = include_bytes!("../../../tests/parity/cube10.stl");
    let output = ares_core::slice(input, ares_core::SliceOptions::default())
        .await
        .unwrap();
    let text = std::str::from_utf8(&output).unwrap();
    let generators: Vec<_> = text
        .lines()
        .filter(|line| line.starts_with("; generated by "))
        .collect();
    assert_eq!(
        generators,
        ["; generated by Ares 2.5.0 on 1980-01-01 at 00:00:00"]
    );
}

#[tokio::test]
async fn btt_omits_automatic_producer_on_both_public_paths() {
    let stl = include_bytes!("../../../tests/parity/cube10.stl");
    let options = serde_json::from_value(serde_json::json!({
        "thumbnails": "32x24/BTT_TFT"
    }))
    .unwrap();
    let bytes = ares_core::slice(stl, options).await.unwrap();
    let project =
        include_bytes!("../../../tests/parity/klipper-separate-jerk-precision/integer-control.3mf");
    let overrides =
        ares_core::ConfigOverrides::from_json(br#"{"thumbnails":"32x24/BTT_TFT"}"#).unwrap();
    let project = ares_core::slice_project_plate_validated(
        project,
        ares_core::GenerationMetadata::default(),
        Some(1),
        &overrides,
        ares_core::SlicerContext::new(0),
    )
    .await
    .unwrap();
    for output in [bytes, project] {
        let text = std::str::from_utf8(&output).unwrap();
        assert!(!text.lines().any(|line| line.starts_with("; generated by ")));
        assert!(!text.contains("; HEADER_BLOCK_START"));
        assert!(!text.contains("; HEADER_BLOCK_END"));
    }
}
