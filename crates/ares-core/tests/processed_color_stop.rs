//! GCodeProcessor stop-time postprocessing, not GCodeGenerator emission.
//! Failure inventory: missing initial/transition C lines; lost SYNC-flushed
//! zero stop entries; incorrect last-minute formatting; changed P/R times or
//! unrelated G-code bytes. Goldens come from the unmodified official slicer.

use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};

const PROJECT: &[u8] = include_bytes!("../../../tests/parity/orca_cli_ender3.3mf");

#[tokio::test]
async fn color_stop_after_sync_matches_official_gcode_bytes() {
    check("normal").await;
}

#[tokio::test]
async fn color_stop_last_minute_matches_official_gcode_bytes() {
    check("stop-times").await;
}

#[tokio::test]
async fn color_stop_before_model_matches_official_gcode_bytes() {
    check("zero-before").await;
}

async fn check(name: &str) {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let fixture = root.join("tests/parity/color-change/m73-stop").join(name);
    let settings = std::fs::read(fixture.join("overrides.json")).unwrap();
    let overrides = ConfigOverrides::from_json(&settings).unwrap();
    let gcode = slice_project_plate(
        PROJECT,
        GenerationMetadata::default(),
        Some(1),
        &overrides,
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    let actual = String::from_utf8(gcode).unwrap();
    assert_eq!(actual.matches("; generated by Ares 2.4.2\n").count(), 1);
    let actual = actual.replacen(
        "; generated by Ares 2.4.2\n",
        "; generated by <SLICER> 2.4.2\n",
        1,
    );
    let expected = std::fs::read(fixture.join("official.gcode")).unwrap();
    let directory = root.join("target/color-change-stop-oracle").join(name);
    std::fs::create_dir_all(&directory).unwrap();
    std::fs::write(directory.join("rust.gcode"), &actual).unwrap();
    std::fs::write(directory.join("official.gcode"), &expected).unwrap();
    let expected = std::str::from_utf8(&expected).unwrap();
    let actual_m73: Vec<_> = actual
        .lines()
        .filter(|line| line.starts_with("M73 "))
        .collect();
    let expected_m73: Vec<_> = expected
        .lines()
        .filter(|line| line.starts_with("M73 "))
        .collect();
    assert!(
        expected_m73.iter().any(|line| line.starts_with("M73 C")),
        "native stop lines must be exercised"
    );
    assert_eq!(
        actual_m73, expected_m73,
        "{name}: original native M73 bytes"
    );
    assert_eq!(
        actual.as_bytes().len(),
        expected.len(),
        "{name}: complete G-code byte length"
    );
    assert!(
        actual.as_bytes() == expected.as_bytes(),
        "{name}: complete G-code bytes; see {}",
        directory.display()
    );
}
