//! Klipper per-role jerk: `is_infill` (ExtrusionEntity.hpp:73-82) excludes
//! `erGapFill` and includes `erIroning`, so gap fill falls to `default_jerk`
//! and ironing takes `infill_jerk` (`GCode.cpp:6440-6458`). The real
//! Ender-5 Max 0.4 `0.20mm Standard` selection (klipper, default_jerk 9 /
//! infill_jerk 20) produces gap-fill sections where the native emits
//! `SET_VELOCITY_LIMIT SQUARE_CORNER_VELOCITY=9` at the gap-fill path start
//! and `=20` at the following infill path; the fixtures are the native 2.4.2
//! export and slice of that selection.

use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};

#[tokio::test]
async fn e5max_klipper_jerk_switches_match_native() {
    let project = std::fs::read(format!(
        "{}/../../tests/parity/validation/e5max-scv/project.3mf",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap();
    let expected = std::fs::read_to_string(format!(
        "{}/../../tests/parity/validation/e5max-scv/expected.gcode",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap();
    let gcode = slice_project_plate(
        project,
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    let actual = String::from_utf8(gcode).unwrap();
    fn normalize(text: &str) -> Vec<&str> {
        text.lines().map(normalize_line).collect()
    }
    fn normalize_line(line: &str) -> &str {
        if line.starts_with("; generated by") {
            "; generated by"
        } else {
            line
        }
    }
    let actual_lines = normalize(&actual);
    let expected_lines = normalize(&expected);
    for (index, (actual, expected)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        assert_eq!(actual, expected, "first mismatch at line {}", index + 1);
    }
    assert_eq!(actual_lines.len(), expected_lines.len());
}
