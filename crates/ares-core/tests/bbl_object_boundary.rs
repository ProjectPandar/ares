//! BBL object-segment emission ordering: the object-end boundary orders
//! [path-end retract+wipe → eager lift → unique-label stop marker + M625
//! flush → fan restore lines → `; CHANGE_LAYER`/`; Z_HEIGHT`/`;
//! LAYER_HEIGHT` (`change_layer` head, GCode.cpp:4618-4627) → layer
//! template], and the object-start boundary emits its lift/travel AFTER the
//! M624 marker flush with an explicit Z-hold before the layer descend. The
//! inter-layer travel re-emits the feedrate on the combined `G1 X Y Z F…`
//! move (`travel_to_xyz`, GCodeWriter.cpp:685-710). M73 insertion and the
//! header time estimate are downstream of this ordering.

use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};

fn fixture(name: &str) -> Vec<u8> {
    std::fs::read(format!(
        "{}/../../tests/parity/validation/{name}",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap()
}

fn normalize(text: &str) -> Vec<&str> {
    fn normalize_line(line: &str) -> &str {
        if line.starts_with("; generated by") {
            "; generated by"
        } else {
            line
        }
    }
    text.lines().map(normalize_line).collect()
}

#[tokio::test]
async fn bbl_object_boundaries_match_native() {
    let gcode = slice_project_plate(
        fixture("bbl-object-boundary.3mf"),
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    let gcode_text = String::from_utf8(gcode.to_vec()).unwrap();
    let actual = normalize(&gcode_text);
    let expected_text = String::from_utf8(fixture("bbl-object-boundary-expected.gcode")).unwrap();
    let expected = normalize(&expected_text);
    for (index, (actual, expected)) in actual.iter().zip(&expected).enumerate() {
        assert_eq!(actual, expected, "first mismatch at line {}", index + 1);
    }
    assert_eq!(actual.len(), expected.len());
}
