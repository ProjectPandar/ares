//! SEMM toolchange temperature emission (`GCode.cpp:8000-8004`):
//! `single_extruder_multi_material && !enable_prime_tower` re-emits the
//! nozzle temperature after every filament change — initial-layer value on
//! the first layer, plain `nozzle_temperature` after — via
//! `set_temperature(temp, false)`, whose writer overload drops the tool
//! index for SEMM (`GCodeWriter.cpp:159-164`, tool forced to -1). The
//! fixture is the real Anycubic Kobra 3 Max project with the three
//! infill-role filament ids aligned (same filament) so the object extruder
//! (filament 1) and infill (filament 2) alternate every layer and
//! `exclude_object` off; the native reference emits one startup
//! `M104 S220` (initial layer) plus 75 per-toolchange `M104 S210` lines,
//! all bare.

use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};

fn fixture(name: &str) -> Vec<u8> {
    std::fs::read(format!(
        "{}/../../tests/parity/validation/{name}",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap()
}

fn normalize(text: &str) -> Vec<&str> {
    fn normalize_line(line: &str) -> &str {
        if line.starts_with("; generated by") {
            "; generated by"
        } else {
            line
        }
    }
    text.lines().map(normalize_line).collect()
}

#[tokio::test]
async fn semm_toolchange_m104_matches_native() {
    let gcode = slice_project_plate(
        fixture("semm-m104-k3m.3mf"),
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    let actual = String::from_utf8(gcode).unwrap();
    let expected = String::from_utf8(fixture("semm-m104-k3m-expected.gcode")).unwrap();
    let actual_lines = normalize(&actual);
    let expected_lines = normalize(&expected);
    for (index, (actual, expected)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        assert_eq!(actual, expected, "first mismatch at line {}", index + 1);
    }
    assert_eq!(actual_lines.len(), expected_lines.len());
}
