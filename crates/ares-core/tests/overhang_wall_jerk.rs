//! Per-role jerk: `is_external_perimeter` covers only `erExternalPerimeter`
//! and `is_internal_perimeter` only `erPerimeter` (ExtrusionEntity.hpp:
//! 59-66), so `erOverhangPerimeter` hits no role arm in the jerk selection
//! (`GCode.cpp:6440-6458`) and falls to `default_jerk`. The fixtures are
//! the native 2.4.2 export and slice of the matrix's real overhang model on
//! the real Creality Ender-3 machine with differentiated jerks
//! (default 9 / outer 7 / inner 7 / infill 12) and unclamped machine jerk
//! limits: every `;TYPE:Overhang wall` path start carries `M205 X9`
//! (the default), not the outer value 7.

use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};

#[tokio::test]
async fn overhang_wall_jerk_matches_native() {
    let project = std::fs::read(format!(
        "{}/../../tests/parity/validation/overhang-jerk/project.3mf",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap();
    let expected = std::fs::read_to_string(format!(
        "{}/../../tests/parity/validation/overhang-jerk/expected.gcode",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap();
    let gcode = slice_project_plate(
        project,
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    let actual = String::from_utf8(gcode).unwrap();
    fn normalize_line(line: &str) -> &str {
        if line.starts_with("; generated by") {
            "; generated by"
        } else {
            line
        }
    }
    fn normalize(text: &str) -> Vec<&str> {
        text.lines().map(normalize_line).collect()
    }
    let actual_lines = normalize(&actual);
    let expected_lines = normalize(&expected);
    for (index, (actual, expected)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        assert_eq!(actual, expected, "first mismatch at line {}", index + 1);
    }
    assert_eq!(actual_lines.len(), expected_lines.len());
}
