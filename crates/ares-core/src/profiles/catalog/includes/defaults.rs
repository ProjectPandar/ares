pub(super) fn contains(kind: ProfileKind, key: &str) -> bool {
    match kind {
        ProfileKind::Process => PROCESS.binary_search(&key).is_ok(),
        ProfileKind::Filament => FILAMENT.binary_search(&key).is_ok(),
        ProfileKind::Machine => {
            PRINTER.binary_search(&key).is_ok()
                || LIMITS.binary_search(&key).is_ok()
                || extruder_option_keys().contains(&key)
        }
    }
}
