#[tokio::test]
async fn malformed_typed_settings_fail_during_project_loading() {
    let metadata = GenerationMetadata::deterministic(2026, 7, 13, 1, 2, 3);
    // Literal duplicate keys now overwrite (upstream `set_deserialize_raw`,
    // Config.cpp:573-587): the later value wins.
    let mut parts = ProjectParts::valid();
    parts.insert_text(
        "Metadata/project_settings.config",
        r#"{"layer_height":"0.2","layer_height":"0.3"}"#,
    );
    let loaded = load_project(parts.bytes()).unwrap();
    assert_eq!(loaded.settings().process.object.layer_height.0, 0.3);
    for (input, key, reason) in [
        (r#"{"future_option":"1"}"#, "", "ignored like orca"),
        (
            r#"{"layer_height":"not-a-float"}"#,
            "layer_height",
            "invalid float literal",
        ),
    ] {
        let mut parts = ProjectParts::valid();
        parts.insert_text("Metadata/project_settings.config", input);
        let bytes = parts.bytes();
        // Unknown keys are skipped (Orca config loader semantics); malformed
        // typed keys still fail the load.
        let message = match load_project(&bytes) {
            Ok(_) if key.is_empty() => continue,
            Ok(_) => panic!("unexpected successful load for {key}"),
            Err(error) => error.to_string(),
        };

        assert!(message.starts_with("invalid project settings JSON: "));
        assert!(message.contains(key), "diagnostic omitted {key}: {message}");
        assert!(
            message.contains(reason),
            "diagnostic omitted {reason}: {message}"
        );
        assert!(
            slice_project(&bytes, metadata, crate::SlicerContext::new(0))
                .await
                .is_err()
        );
    }
}

#[test]
fn scalar_strings_coerce_to_single_element_vectors() {
    // `ConfigBase::load_from_json` routes every JSON string through
    // `set_deserialize` (`Config.cpp:927-929`) regardless of the target
    // option type; `ConfigOptionVector::deserialize` (`Config.hpp:868-887`)
    // splits on `,` so a bare scalar becomes a one-element vector.
    for (input, check) in [
        (
            r#"{"idle_temperature":"180"}"#,
            Box::new(|settings: &crate::ProjectSettings| {
                assert_eq!(
                    settings.filament.print.idle_temperature.0,
                    vec![crate::OrcaInt(180)]
                );
            }) as Box<dyn Fn(&crate::ProjectSettings)>,
        ),
        (
            r#"{"activate_chamber_temp_control":"0"}"#,
            Box::new(|settings: &crate::ProjectSettings| {
                assert_eq!(
                    settings.filament.print.activate_chamber_temp_control.0,
                    vec![crate::OrcaBool(false)]
                );
            }) as Box<dyn Fn(&crate::ProjectSettings)>,
        ),
        (
            r#"{"default_filament_colour":""}"#,
            Box::new(|settings: &crate::ProjectSettings| {
                assert!(settings.filament.gcode.default_filament_colour.0.is_empty());
            }) as Box<dyn Fn(&crate::ProjectSettings)>,
        ),
    ] {
        let mut parts = ProjectParts::valid();
        parts.insert_text("Metadata/project_settings.config", input);
        let loaded =
            load_project(parts.bytes()).unwrap_or_else(|error| panic!("{input} rejected: {error}"));
        check(loaded.settings());
    }
}
