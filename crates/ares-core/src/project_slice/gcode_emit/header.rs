use super::super::perimeters::classic::traversal::PreparedPostClassicTraversal;
use crate::GenerationMetadata;

pub(super) fn enabled(traversal: &PreparedPostClassicTraversal) -> bool {
    // GCode::do_export omits the entire header for a BTT thumbnail list.
    !traversal
        .resolved
        .views
        .full
        .printer
        .remaining
        .thumbnails
        .as_str()
        .contains("BTT_TFT")
}

pub(super) fn append_header(
    output: &mut Vec<u8>,
    metadata: GenerationMetadata,
    traversal: &PreparedPostClassicTraversal,
    layers: usize,
    max_z: f64,
) {
    let (year, month, day, hour, minute, second) = metadata.timestamp();
    let label_id = traversal
        .project
        .objects()
        .first()
        .and_then(|object| object.instances().first())
        .map_or(0, |instance| instance.loaded_label_id());
    let density = format_values(
        &traversal
            .resolved
            .views
            .full
            .filament
            .gcode
            .filament_density
            .0,
    );
    let diameter = format_values(
        &traversal
            .resolved
            .views
            .full
            .filament
            .gcode
            .filament_diameter
            .0,
    );
    // `GCode.cpp:2612-2618`: the max print z over every object's last
    // layer (raft layers included through the shifted object z chain).
    let filament_count = traversal.resolved.usage.supported_used_filaments.len();
    output.extend_from_slice(b"; HEADER_BLOCK_START\n");
    output.extend_from_slice(
        format!(
            "; generated by Ares 2.4.2 on {year:04}-{month:02}-{day:02} at {hour:02}:{minute:02}:{second:02}\n"
        )
        .as_bytes(),
    );
    let tags = super::tags::Tags::of(traversal);
    // `GCode.cpp:2578-2608`: BBL printers carry the time placeholders in
    // the header; the compatible flavor keeps them at the file tail next to
    // the klipper-style statistics.
    if tags.is_bbl() {
        output.extend_from_slice(b"; model printing time: 0s; total estimated time: 0s\n");
        output.extend_from_slice(b"; estimated first layer printing time (normal mode) = 0s\n");
    }
    output.extend_from_slice(format!("; total layer number: {layers}\n").as_bytes());
    (tags.is_bbl())
        .then(|| output.extend_from_slice(format!("; model label id: {label_id}\n").as_bytes()));
    output.extend_from_slice(format!("; filament_density: {density}\n").as_bytes());
    output.extend_from_slice(format!("; filament_diameter: {diameter}\n").as_bytes());
    output.extend_from_slice(format!("; max_z_height: {max_z:.2}\n").as_bytes());
    output.extend_from_slice(format!("; filament: {filament_count}\n").as_bytes());
    output.extend_from_slice(b"; HEADER_BLOCK_END\n\n");
}

pub(super) fn finalize_layer_count(output: &mut Vec<u8>, layers: usize) -> usize {
    let prefix = b"; total layer number: ";
    let start = output
        .windows(prefix.len())
        .position(|window| window == prefix)
        .expect("generated header contains its layer-count field")
        + prefix.len();
    let end = output[start..]
        .iter()
        .position(|byte| *byte == b'\n')
        .expect("generated layer-count field is line terminated")
        + start;
    output.splice(start..end, layers.to_string().bytes());
    layers
}

fn format_values(values: &[crate::OrcaFloat]) -> String {
    values
        .iter()
        .map(|value| value.0.to_string())
        .collect::<Vec<_>>()
        .join(",")
}

pub(super) fn append_width_block(
    output: &mut Vec<u8>,
    traversal: &PreparedPostClassicTraversal,
) -> Result<(), crate::SliceError> {
    let first_source = traversal.objects[0]
        .predecessor
        .predecessor
        .predecessor
        .predecessor
        .object
        .identity()
        .0;
    let first = &traversal
        .resolved
        .objects
        .iter()
        .find(|object| object.source_object_index == first_source)
        .expect("first print object retains its resolved source")
        .object;
    let has_support = traversal.resolved.objects.iter().any(|object| {
        object.object.enable_support.0
            || object.object.enforce_support_layers.0 > 0
            || object.object.raft_layers.0 > 0
    });
    // PrintApply.cpp's shared-region loop never inserts into region_set.
    for object in &traversal.resolved.objects {
        for region in &object.all_regions {
            append_region_width_block(output, traversal, first, region, has_support)?;
        }
    }
    Ok(())
}

fn append_region_width_block(
    output: &mut Vec<u8>,
    traversal: &PreparedPostClassicTraversal,
    object_options: &crate::ObjectOptions,
    region: &crate::RegionOptions,
    has_support: bool,
) -> Result<(), crate::SliceError> {
    let settings = &traversal.resolved.views.full;
    let nozzles = &settings.project.print.nozzle_diameter;
    let widths = [
        (
            region.outer_wall_line_width,
            region.outer_wall_filament_id,
            1.125,
        ),
        (
            region.inner_wall_line_width,
            region.inner_wall_filament_id,
            1.125,
        ),
        (
            region.sparse_infill_line_width,
            region.sparse_infill_filament_id,
            1.125,
        ),
        (
            region.internal_solid_infill_line_width,
            region.internal_solid_filament_id,
            1.125,
        ),
        (
            region.top_surface_line_width,
            region.top_surface_filament_id,
            1.0,
        ),
    ];
    let labels = [
        "external perimeters",
        "perimeters",
        "infill",
        "solid infill",
        "top infill",
    ];
    for (label, (configured, selector, ratio)) in labels.into_iter().zip(widths) {
        let nozzle = f64::from(super::super::perimeters::flow::selected_nozzle(
            selector, nozzles,
        )?);
        let width = resolved_width(configured, object_options.line_width, nozzle, ratio);
        output.extend_from_slice(format!("; {label} extrusion width = {width:.2}mm\n").as_bytes());
    }
    if has_support {
        let nozzle = f64::from(super::super::perimeters::flow::selected_nozzle(
            object_options.support_filament,
            nozzles,
        )?);
        let width = resolved_width(
            object_options.support_line_width,
            object_options.line_width,
            nozzle,
            1.0,
        );
        output.extend_from_slice(
            format!("; support material extrusion width = {width:.2}mm\n").as_bytes(),
        );
    }
    let nozzle = f64::from(super::super::perimeters::flow::selected_nozzle(
        region.inner_wall_filament_id,
        nozzles,
    )?);
    if let Some(width) = width(settings.process.print.initial_layer_line_width, nozzle) {
        output.extend_from_slice(
            format!("; first layer extrusion width = {width:.2}mm\n").as_bytes(),
        );
    }
    output.push(b'\n');
    Ok(())
}

pub(crate) fn resolved_width(
    configured: crate::FloatOrPercent,
    fallback: crate::FloatOrPercent,
    nozzle: f64,
    automatic_ratio: f64,
) -> f32 {
    width(configured, nozzle)
        .or_else(|| width(fallback, nozzle))
        .unwrap_or_else(|| auto_width(automatic_ratio, nozzle))
}

fn width(value: crate::FloatOrPercent, nozzle: f64) -> Option<f32> {
    match value {
        crate::FloatOrPercent::Float(value) if value > 0.0 => Some(value as f32),
        crate::FloatOrPercent::Percent(value) if value.0 > 0.0 => {
            // `Flow::new_from_config_width` (`Flow.cpp:129-144`) takes the
            // nozzle as FLOAT and resolves the percent through
            // `get_abs_value(double)` — the nozzle f32 round-trip moves
            // boundary cases like 0.3×115% across the 0.345 rounding edge
            // (0.34500001 → "0.35" instead of 0.345 → "0.34").
            Some((value.0 * f64::from(nozzle as f32) / 100.0) as f32)
        }
        _ => None,
    }
}

/// `Flow::auto_extrusion_width` (`Flow.cpp`): the automatic ratio
/// multiplies in FLOAT.
fn auto_width(automatic_ratio: f64, nozzle: f64) -> f32 {
    (automatic_ratio as f32) * (nozzle as f32)
}
