use super::*;

#[tokio::test]
async fn single_filament_cooling_moves_reaches_gcode_config_header() {
    let output = filament_cooling_moves_output(json!({
        "filament_cooling_moves": [4]
    }))
    .await
    .unwrap();

    assert!(
        output
            .lines()
            .any(|line| line == "; filament_cooling_moves = 4")
    );
}

