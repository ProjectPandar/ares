use super::*;

const FILAMENT_STAMPING_KEYS: [&str; 2] = [
    "filament_stamping_loading_speed",
    "filament_stamping_distance",
];

#[tokio::test]
async fn filament_stamping_values_reach_gcode_config_header() {
    let output = filament_stamping_output(json!({
        "filament_stamping_loading_speed": [1.5],
        "filament_stamping_distance": [12.25]
    }))
    .await
    .unwrap();

    for expected in [
        "; filament_stamping_loading_speed = 1.5",
        "; filament_stamping_distance = 12.25",
    ] {
        assert!(output.lines().any(|line| line == expected), "{expected}");
    }
}

#[tokio::test]
async fn multiple_filament_stamping_values_reach_gcode_config_header() {
    let output = filament_stamping_output(json!({
        "filament_stamping_loading_speed": [0.0, 1.5, 3.25],
        "filament_stamping_distance": [0.0, 12.25]
    }))
    .await
    .unwrap();

    assert!(
        output
            .lines()
            .any(|line| line == "; filament_stamping_loading_speed = 0,1.5,3.25")
    );
    assert!(
        output
            .lines()
            .any(|line| line == "; filament_stamping_distance = 0,12.25")
    );
}

