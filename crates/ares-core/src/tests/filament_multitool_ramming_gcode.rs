use super::*;

const FILAMENT_MULTITOOL_RAMMING_KEYS: [&str; 3] = [
    "filament_multitool_ramming",
    "filament_multitool_ramming_volume",
    "filament_multitool_ramming_flow",
];

#[tokio::test]
async fn filament_multitool_ramming_values_reach_gcode_config_header() {
    let output = filament_multitool_ramming_output(json!({
        "filament_multitool_ramming": [true],
        "filament_multitool_ramming_volume": [10.0],
        "filament_multitool_ramming_flow": [12.5]
    }))
    .await
    .unwrap();

    for expected in [
        "; filament_multitool_ramming = 1",
        "; filament_multitool_ramming_volume = 10",
        "; filament_multitool_ramming_flow = 12.5",
    ] {
        assert!(output.lines().any(|line| line == expected), "{expected}");
    }
}

#[tokio::test]
async fn multiple_filament_multitool_ramming_values_reach_gcode_config_header() {
    let output = filament_multitool_ramming_output(json!({
        "filament_multitool_ramming": [true, false],
        "filament_multitool_ramming_volume": [0.0, 10.0, 22.5],
        "filament_multitool_ramming_flow": [0.0, 8.25]
    }))
    .await
    .unwrap();

    assert!(
        output
            .lines()
            .any(|line| line == "; filament_multitool_ramming = 1,0")
    );
    assert!(
        output
            .lines()
            .any(|line| line == "; filament_multitool_ramming_volume = 0,10,22.5")
    );
    assert!(
        output
            .lines()
            .any(|line| line == "; filament_multitool_ramming_flow = 0,8.25")
    );
}

