use super::*;

#[tokio::test]
async fn single_filament_cooling_initial_speed_reaches_gcode_config_header() {
    let output = filament_cooling_initial_speed_output(json!({
        "filament_cooling_initial_speed": [2.2]
    }))
    .await
    .unwrap();

    assert!(
        output
            .lines()
            .any(|line| line == "; filament_cooling_initial_speed = 2.2")
    );
}

