use super::*;

const MMU_SCALAR_CONFIG_KEYS: [&str; 8] = [
    "cooling_tube_retraction",
    "cooling_tube_length",
    "high_current_on_filament_swap",
    "parking_pos_retraction",
    "extra_loading_move",
    "machine_load_filament_time",
    "machine_tool_change_time",
    "machine_unload_filament_time",
];

#[tokio::test]
async fn mmu_scalar_config_values_reach_gcode_config_header() {
    let output = mmu_scalar_config_output(json!({
        "cooling_tube_retraction": 91.5,
        "cooling_tube_length": 5.0,
        "high_current_on_filament_swap": true,
        "parking_pos_retraction": 92.0,
        "extra_loading_move": -2.25,
        "machine_load_filament_time": 1.5,
        "machine_tool_change_time": 2.0,
        "machine_unload_filament_time": 3.25
    }))
    .await
    .unwrap();

    for expected in [
        "; cooling_tube_retraction = 91.5",
        "; cooling_tube_length = 5",
        "; high_current_on_filament_swap = 1",
        "; parking_pos_retraction = 92",
        "; extra_loading_move = -2.25",
        "; machine_load_filament_time = 1.5",
        "; machine_tool_change_time = 2",
        "; machine_unload_filament_time = 3.25",
    ] {
        assert!(output.lines().any(|line| line == expected), "{expected}");
    }
}

