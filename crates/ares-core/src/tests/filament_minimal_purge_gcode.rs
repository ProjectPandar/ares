use super::*;

#[tokio::test]
async fn single_filament_minimal_purge_reaches_gcode_config_header() {
    let output = filament_minimal_purge_output(json!({
        "filament_minimal_purge_on_wipe_tower": [15.0]
    }))
    .await
    .unwrap();

    assert!(
        output
            .lines()
            .any(|line| line == "; filament_minimal_purge_on_wipe_tower = 15")
    );
}

