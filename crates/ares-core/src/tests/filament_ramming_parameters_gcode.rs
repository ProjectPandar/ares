use super::*;

#[tokio::test]
async fn single_filament_ramming_parameters_reaches_gcode_config_header() {
    let output = filament_ramming_parameters_output(json!({
        "filament_ramming_parameters": ["120 100 6.6 6.8"]
    }))
    .await
    .unwrap();

    assert!(
        output
            .lines()
            .any(|line| line == "; filament_ramming_parameters = \"120 100 6.6 6.8\"")
    );
}

