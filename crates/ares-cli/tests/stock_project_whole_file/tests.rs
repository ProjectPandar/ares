#[test]
fn generator_normalization_changes_only_the_validated_line() {
    let orca = b"before\n; generated by OrcaSlicer 2.5.0-beta on 2026-07-10 at 11:16:09\nafter\n";
    let ares = b"before\n; generated by Ares 2.5.0-beta\nafter\n";
    let expected = b"before\n; generated by <SLICER> 2.5.0-beta\nafter\n";

    assert_eq!(
        normalize_one_generator_line(orca, GeneratorKind::Orca).unwrap(),
        expected
    );
    assert_eq!(
        normalize_one_generator_line(ares, GeneratorKind::Ares).unwrap(),
        expected
    );
}

#[test]
fn generator_normalization_requires_exactly_one_complete_utf8_line() {
    assert_eq!(
        normalize_one_generator_line(b"no generator line\n", GeneratorKind::Orca).unwrap_err(),
        "expected one OrcaSlicer generator line, found 0"
    );
    assert_eq!(
        normalize_one_generator_line(
            b"; generated by OrcaSlicer 2.5.0-beta on 2026-07-10 at 11:16:09\n; generated by OrcaSlicer 2.5.0-beta on 2026-07-10 at 11:16:10\n",
            GeneratorKind::Orca,
        )
        .unwrap_err(),
        "expected one OrcaSlicer generator line, found 2"
    );
    assert!(
        normalize_one_generator_line(
            b"prefix ; generated by OrcaSlicer 2.5.0-beta on 2026-07-10 at 11:16:09\n",
            GeneratorKind::Orca,
        )
        .is_err()
    );
    assert!(normalize_one_generator_line(&[0xff], GeneratorKind::Orca).is_err());
}

#[test]
fn generator_normalization_masks_vendor_branded_timestamp_lines() {
    let orca = b"; HEADER_BLOCK_START\n; generated by Creality_Print V7.0.1.4212 on 2026-9-13 at 5:31:39\n; total layer number: 125\n; generated by OrcaSlicer 2.5.0-beta on 2026-07-10 at 11:16:09\n";
    let ares = b"; HEADER_BLOCK_START\n; generated by Creality_Print V7.0.1.4212 on 2026-8-27 at 0:0:0\n; total layer number: 125\n; generated by Ares 2.5.0-beta\n";

    let normalized_orca = normalize_one_generator_line(orca, GeneratorKind::Orca).unwrap();
    let normalized_ares = normalize_one_generator_line(ares, GeneratorKind::Ares).unwrap();
    assert_eq!(normalized_orca, normalized_ares);
    assert!(
        String::from_utf8(normalized_orca)
            .unwrap()
            .contains("; generated by Creality_Print V7.0.1.4212 on <DATE> at <TIME>")
    );
}

#[test]
fn generator_normalization_preserves_vendor_brand_and_version() {
    // The brand/version of a vendor-branded generated-by line is behavioral
    // (the Creality K2 header exists to suppress a printer warning); only the
    // local-time identity may differ between the producers.
    let orca = b"; generated by Creality_Print V7.0.1.4212 on 2026-9-13 at 5:31:39\n; generated by OrcaSlicer 2.5.0-beta on 2026-07-10 at 11:16:09\n";
    let rebranded = b"; generated by Creality_Print V9.9.9.9999 on 2026-9-13 at 5:31:39\n; generated by OrcaSlicer 2.5.0-beta on 2026-07-10 at 11:16:09\n";

    let normalized = normalize_one_generator_line(orca, GeneratorKind::Orca).unwrap();
    let mutated = normalize_one_generator_line(rebranded, GeneratorKind::Orca).unwrap();
    assert_ne!(normalized, mutated);
    assert!(
        String::from_utf8(mutated)
            .unwrap()
            .contains("V9.9.9.9999 on <DATE> at <TIME>")
    );
}

#[test]
fn first_difference_reports_bounded_three_line_context() {
    let expected = b"line1\nline2\nline3\nline4\nline5\n";
    let actual = b"line1\nline2\nLINE3\nline4\nline5\n";

    let difference = first_difference(expected, actual).unwrap().to_string();

    assert_eq!(
        difference,
        "first difference at byte 12 (line 3, column 1; expected 30 bytes, actual 30 bytes)\ncontext:\n  line 2: \"line2\"\n  line 3: expected \"line3\"; actual \"LINE3\"\n  line 4: \"line4\""
    );
    assert!(first_difference(expected, expected).is_none());
}

#[test]
fn first_difference_truncates_long_context_lines() {
    let expected = format!("before\n{}x\nafter\n", "a".repeat(10_000));
    let actual = format!("before\n{}y\nafter\n", "a".repeat(10_000));

    let difference = first_difference(expected.as_bytes(), actual.as_bytes())
        .unwrap()
        .to_string();

    assert!(difference.len() < 1_024);
    assert_eq!(
        difference
            .lines()
            .filter(|line| line.starts_with("  line "))
            .count(),
        3
    );
}
