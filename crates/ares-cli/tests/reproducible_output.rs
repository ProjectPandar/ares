use std::{fs, path::Path};

#[test]
fn project_output_is_reproducible_across_processes_with_epoch_metadata() {
    let directory = tempfile::tempdir().unwrap();
    let input =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/processor_output_isolation/project.3mf");
    let outputs = ["first.gcode", "second.gcode"].map(|name| {
        let output = directory.path().join(name);
        assert_cmd::cargo::cargo_bin_cmd!("ares")
            .arg("slice")
            .arg("-o")
            .arg(&output)
            .arg(&input)
            .assert()
            .success();
        fs::read(output).unwrap()
    });
    assert!(
        std::str::from_utf8(&outputs[0])
            .unwrap()
            .contains("; generated by Ares 2.4.2 on 1970-01-01 at 00:00:00\n")
    );
    assert_eq!(outputs[0], outputs[1]);
}
