use std::{
    fs,
    io::{Cursor, Read, Write},
    path::Path,
};

#[test]
fn project_output_is_reproducible_across_processes_with_fixed_producer_marker() {
    let directory = tempfile::tempdir().unwrap();
    let input =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/processor_output_isolation/project.3mf");
    let outputs = [
        ("first.gcode", "Pacific/Kiritimati"),
        ("second.gcode", "America/Adak"),
    ]
    .map(|(name, timezone)| {
        let output = directory.path().join(name);
        assert_cmd::cargo::cargo_bin_cmd!("ares")
            .env("TZ", timezone)
            .arg("slice")
            .arg("-o")
            .arg(&output)
            .arg(&input)
            .assert()
            .success();
        fs::read(output).unwrap()
    });
    assert_eq!(
        std::str::from_utf8(&outputs[0])
            .unwrap()
            .lines()
            .find(|line| line.starts_with("; generated by Ares ")),
        Some("; generated by Ares 2.5.0 on 1980-01-01 at 00:00:00")
    );
    assert_eq!(outputs[0], outputs[1]);
}

#[test]
fn saved_project_templates_retain_all_epoch_time_variables() {
    let directory = tempfile::tempdir().unwrap();
    let input =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/processor_output_isolation/project.3mf");
    let mut source = zip::ZipArchive::new(Cursor::new(fs::read(input).unwrap())).unwrap();
    let mut archive = zip::ZipWriter::new(Cursor::new(Vec::new()));
    for index in 0..source.len() {
        let mut entry = source.by_index(index).unwrap();
        let mut bytes = Vec::new();
        entry.read_to_end(&mut bytes).unwrap();
        if entry.name() == "Metadata/project_settings.config" {
            let mut config: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
            config["file_start_gcode"] = serde_json::json!(
                "; clock {timestamp} {year} {month} {day} {hour} {minute} {second}"
            );
            bytes = serde_json::to_vec(&config).unwrap();
        }
        archive
            .start_file(entry.name(), zip::write::SimpleFileOptions::DEFAULT)
            .unwrap();
        archive.write_all(&bytes).unwrap();
    }
    let project = directory.path().join("clock.3mf");
    fs::write(&project, archive.finish().unwrap().into_inner()).unwrap();
    let output = directory.path().join("clock.gcode");
    assert_cmd::cargo::cargo_bin_cmd!("ares")
        .args(["slice", "-o"])
        .arg(&output)
        .arg(&project)
        .assert()
        .success();
    let text = fs::read_to_string(output).unwrap();
    assert!(text.starts_with("; clock 19700101-000000 1970 1 1 0 0 0\n"));
}
