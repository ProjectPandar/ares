use std::collections::BTreeMap;

#[derive(Debug)]
pub(crate) struct SemanticGcode {
    pub(super) timing: Timing,
    pub(super) filament_lengths: Vec<f64>,
    pub(super) preamble: Vec<String>,
    pub(super) postamble: Vec<String>,
    /// Ordered `M73 P.. R..` progress lines — previously discarded
    /// entirely, which made a deleted or reordered progress emission
    /// invisible to the comparison.
    pub(super) progress: Vec<String>,
    /// `; CONFIG_BLOCK_START..END` payload lines, kept unsorted so a
    /// reordered block still surfaces.
    pub(super) config_block: Vec<String>,
    pub(crate) layers: Vec<Layer>,
}

#[derive(Debug, Default)]
pub(crate) struct Layer {
    pub(super) metadata: Vec<String>,
    pub(crate) deposition: Vec<Deposition>,
    pub(super) lifecycles: Vec<Vec<LifecycleEvent>>,
    pub(super) travels: Vec<Travel>,
    pub(super) controls: Vec<String>,
}

#[derive(Debug)]
pub(crate) struct Deposition {
    pub(crate) feature: String,
    pub(crate) width: String,
    pub(crate) motion: MotionRecord,
    pub(crate) extrusion: String,
    pub(crate) feed: f64,
    pub(crate) acceleration: String,
    pub(crate) fans: String,
}

#[derive(Debug)]
pub(super) struct Travel {
    pub(super) motion: MotionRecord,
    pub(super) feed: f64,
    pub(super) acceleration: String,
}

#[derive(Default)]
struct State {
    x: String,
    y: String,
    z: String,
    feed: String,
    print_acceleration: String,
    travel_acceleration: String,
    feature: String,
    width: String,
    fans: BTreeMap<String, String>,
    // Active arc plane (G17/G18/G19); motion records snapshot it so a
    // plane change cannot detach from the arc it reorients.
    plane: String,
}

pub(crate) fn parse(bytes: &[u8]) -> Result<SemanticGcode, String> {
    let text = std::str::from_utf8(bytes).map_err(|error| error.to_string())?;
    let mut output = SemanticGcode {
        timing: Timing::default(),
        filament_lengths: Vec::new(),
        preamble: Vec::new(),
        postamble: Vec::new(),
        progress: Vec::new(),
        config_block: Vec::new(),
        layers: Vec::new(),
    };
    let mut state = State {
        plane: "G17".to_owned(),
        ..State::default()
    };
    let mut final_object_stopped = false;
    let mut in_postamble = false;
    let mut in_config_block = false;

    for raw_line in text.lines() {
        // The generator stamp embeds producer name and wall-clock time;
        // canonicalize it so cross-slicer comparisons stay structural.
        let generated_line = raw_line
            .starts_with("; generated by ")
            .then(|| "; generated by <producer>".to_owned());
        let raw_line: &str = generated_line.as_deref().unwrap_or(raw_line);
        let line = raw_line.trim();
        let command_line = line.split_once(';').map_or(line, |(code, _)| code).trim();
        let semantic_line = if command_line.is_empty() {
            raw_line
        } else {
            command_line
        };
        if parse_timing(line, &mut output.timing)? {
            continue;
        }
        if let Some(lengths) = parse_filament_lengths(line)? {
            output.filament_lengths = lengths;
            continue;
        }
        if line.starts_with("M73 ") {
            output.progress.push(line.to_owned());
            continue;
        }
        if line == "; CONFIG_BLOCK_START" {
            in_config_block = true;
            continue;
        }
        if in_config_block {
            if line == "; CONFIG_BLOCK_END" {
                in_config_block = false;
            } else {
                output.config_block.push(semantic_line.to_owned());
            }
            continue;
        }
        if in_postamble {
            if !semantic_line.trim().is_empty() && !ignored_postamble_stat(line) {
                output.postamble.push(semantic_line.to_owned());
            }
            continue;
        }
        if final_object_stopped && command_line == "M106 S0" {
            in_postamble = true;
            output.postamble.push(command_line.to_owned());
            continue;
        }
        if line.starts_with("; stop printing object") {
            final_object_stopped = true;
        }
        if line == "; CHANGE_LAYER" || line == ";LAYER_CHANGE" {
            output.layers.push(Layer::default());
            continue;
        }
        if let Some(value) = line
            .strip_prefix("; FEATURE: ")
            .or_else(|| line.strip_prefix(";TYPE:"))
        {
            state.feature = value.to_owned();
            continue;
        }
        if let Some(value) = line
            .strip_prefix("; LINE_WIDTH: ")
            .or_else(|| line.strip_prefix(";WIDTH:"))
        {
            state.width = canonical_number(value)?;
            continue;
        }
        if line == "; WIPE_START" || line == ";WIPE_START" {
            push_lifecycle(current_layer(&mut output)?, LifecycleEvent::WipeStart);
            continue;
        }
        if line == "; WIPE_END" || line == ";WIPE_END" {
            push_lifecycle(current_layer(&mut output)?, LifecycleEvent::WipeEnd);
            continue;
        }
        if line
            .strip_prefix("; Z_HEIGHT: ")
            .or_else(|| line.strip_prefix(";Z:"))
            .is_some()
        {
            // Layer metadata only: machine Z changes solely through motion
            // commands. Seeding `state.z` here would let a comment mask a
            // missing physical `G1 Z` move.
            if let Some(layer) = output.layers.last_mut() {
                layer.metadata.push(raw_line.to_owned());
            } else {
                output.preamble.push(raw_line.to_owned());
            }
            continue;
        }
        if line.starts_with("; LAYER_HEIGHT: ") || line.starts_with(";HEIGHT:") {
            if let Some(layer) = output.layers.last_mut() {
                layer.metadata.push(raw_line.to_owned());
            } else {
                output.preamble.push(raw_line.to_owned());
            }
            continue;
        }
        if update_acceleration(command_line, &mut state)? {
            if output.layers.is_empty() {
                output.preamble.push(command_line.to_owned());
            }
            continue;
        }
        if command_line.starts_with("M106 ") {
            update_fan(command_line, &mut state)?;
            push_control(&mut output, command_line);
            continue;
        }
        if matches!(command_line, "G17" | "G18" | "G19") {
            state.plane = command_line.to_owned();
            push_control(&mut output, command_line);
            continue;
        }
        if command_line == "M107" || command_line.starts_with("M107 ") {
            // M107 turns the (default) fan off: deposition fan snapshots
            // must see it, so update state like M106 S0.
            let mut fan = "0".to_owned();
            for value in command_line
                .split_whitespace()
                .skip(1)
                .filter_map(|token| token.strip_prefix('P'))
            {
                fan = canonical_number(value)?;
            }
            state.fans.insert(fan, "0".to_owned());
            push_control(&mut output, command_line);
            continue;
        }
        if let Some(motion) = Motion::parse(command_line)? {
            if output.layers.is_empty() {
                output.preamble.push(command_line.to_owned());
            }
            apply_motion(&mut output, &mut state, motion)?;
            continue;
        }
        push_control(&mut output, semantic_line);
    }

    if output.layers.is_empty() {
        return Err("G-code contains no layers".to_owned());
    }
    if output.filament_lengths.is_empty() {
        return Err("G-code contains no filament length statistics".to_owned());
    }
    for layer in &mut output.layers {
        layer.deposition.sort_by(|left, right| {
            left.feature
                .cmp(&right.feature)
                .then_with(|| left.width.cmp(&right.width))
                .then_with(|| left.motion.cmp(&right.motion))
                .then_with(|| left.extrusion.cmp(&right.extrusion))
                .then_with(|| left.acceleration.cmp(&right.acceleration))
                .then_with(|| left.fans.cmp(&right.fans))
                .then_with(|| left.feed.total_cmp(&right.feed))
        });
        layer.lifecycles.sort_unstable();
    }
    Ok(output)
}

fn push_control(output: &mut SemanticGcode, line: &str) {
    if let Some(layer) = output.layers.last_mut() {
        layer.controls.push(line.to_owned());
    } else {
        output.preamble.push(line.to_owned());
    }
}

fn current_layer(output: &mut SemanticGcode) -> Result<&mut Layer, String> {
    output
        .layers
        .last_mut()
        .ok_or_else(|| "layer metadata appears before CHANGE_LAYER".to_owned())
}

fn update_acceleration(line: &str, state: &mut State) -> Result<bool, String> {
    if line.split_ascii_whitespace().next() != Some("M204") {
        return Ok(false);
    }
    for token in line.split_ascii_whitespace().skip(1) {
        let Some(key @ ('S' | 'P' | 'T')) = token.chars().next() else {
            continue;
        };
        let value = canonical_number(&token[1..])?;
        match key {
            'S' => {
                state.print_acceleration.clone_from(&value);
                state.travel_acceleration = value;
            }
            'P' => state.print_acceleration = value,
            'T' => state.travel_acceleration = value,
            _ => unreachable!(),
        }
    }
    Ok(true)
}

fn update_fan(line: &str, state: &mut State) -> Result<(), String> {
    let mut fan = "0".to_owned();
    let mut speed = None;
    for token in line.split_whitespace().skip(1) {
        if let Some(value) = token.strip_prefix('P') {
            fan = canonical_number(value)?;
        } else if let Some(value) = token.strip_prefix('S') {
            speed = Some(canonical_number(value)?);
        }
    }
    // `M106 P<n> S<v>` sets the speed; `M106 P<n>` alone (Prusa CORE One L
    // bed/chamber fan commands with R/A/B/N/G parameters) leaves it
    // unchanged — no state update, the control event still records.
    if let Some(speed) = speed {
        state.fans.insert(fan, speed);
    }
    Ok(())
}

