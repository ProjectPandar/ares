//! `bridge_over_infill` multi-filament parity: project-level
//! `sparse_infill_filament_id=2` with walls on filament 1 (Kobra 3 Max,
//! two loaded filaments). Native slices it; ares' ares-only equality guard
//! (`anchor_projection.rs` `bridge_over_infill_anchor_extruder_order`)
//! wrongly rejects. Upstream `PrintObject::bridge_over_infill`
//! (`PrintObject.cpp:2468+`) is extruder-agnostic — rewritten surfaces stay
//! in their LayerRegion and emit on the region's role filament
//! (`Fill.cpp:865`, `Fill.cpp:920-924`).
//!
//! The fixture narrows unrelated emission families: `exclude_object=0`
//! (the EXCLUDE_OBJECT_DEFINE vertex outline is a separate upstream
//! divergence — see /tmp/ares-matrix-clusters.md) and the source input
//! already disables the prime tower.

use std::fs;

use crate::runner::{OrcaRunner, stages};

const INPUT: &[u8] =
    include_bytes!("../../../../tests/parity/validation/k3m-bridge-over-infill-filament.3mf");
const INPUT_SHA256: &str = "266073a3b15d47e962f4b576e81b564424b56263d124db1e6c7a3b5cd2e7f8fd";

#[test]
fn orca_parity_bridge_over_infill_multi_filament() {
    assert_parity(INPUT, INPUT_SHA256);
}

#[test]
fn orca_parity_bridge_over_infill_multi_filament_x2d() {
    assert_parity(
        include_bytes!(
            "../../../../tests/parity/validation/multi-filament-bridge-anchor-narrowed.3mf"
        ),
        "22d3813ddbbfbc40bd3955fb35d5f6d19b7d8ee23472e7aa2e354e50a23cfe82",
    );
}

fn assert_parity(input_bytes: &[u8], input_sha256: &str) {
    use sha2::{Digest, Sha256};
    assert_eq!(
        Sha256::digest(input_bytes)
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>(),
        input_sha256
    );
    let Some(runner) = OrcaRunner::from_env().unwrap_or_else(|error| panic!("{error}")) else {
        return;
    };
    let directory = tempfile::Builder::new()
        .prefix("bridge-multi-")
        .tempdir()
        .unwrap()
        .keep();
    let input = directory.join("input.3mf");
    fs::write(&input, input_bytes).unwrap();
    let output = directory.join("orca");
    fs::create_dir(&output).unwrap();
    stages::run(
        runner.bin(),
        [
            "--slice".to_owned(),
            "0".to_owned(),
            "--outputdir".to_owned(),
            output.to_str().unwrap().to_owned(),
            input.to_str().unwrap().to_owned(),
        ],
        stages::Stage::Slice,
        &directory,
    )
    .unwrap();
    let reference = stages::read(&output.join("plate_1.gcode"), stages::Stage::Slice).unwrap();

    let actual_bytes = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap()
        .block_on(ares_core::slice_project(
            input_bytes,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();

    fs::write(directory.join("ares.gcode"), &actual_bytes).unwrap();

    // Preserve every other byte, including line endings and the final terminator.
    let strip = |bytes: &[u8]| -> Vec<u8> {
        bytes
            .split_inclusive(|byte| *byte == b'\n')
            .filter(|line| !line.starts_with(b"; generated by"))
            .flatten()
            .copied()
            .collect()
    };
    assert_eq!(strip(&actual_bytes), strip(&reference));
}
