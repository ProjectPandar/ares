//! Runtime Native EXCLUDE_OBJECT_DEFINE hull comparisons, not frozen output.
//! Model.cpp:2625-2644, Point.hpp:665-670, Geometry/ConvexHull.cpp:12-40,
//! GCode.cpp:8059-8072,8096-8106. Identity and rotation-residue inputs retain
//! the original complete ordered-line/line-count comparison, including polygon,
//! layers, role/fan, M73 and CONFIG_BLOCK; only generated-by is normalized.
//! See native-artifact-cleanup-exclude-outline-spec.md. OrcaRunner owns
//! required/optional dependency policy and slice_case caching.

use super::{ExportedCase, OrcaRunner, cache_identity, repo_root};
use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};
use std::fs;

async fn check(fixture: &str) {
    let Some(runner) = OrcaRunner::from_env().unwrap() else {
        return;
    };
    let source = repo_root().join("tests/parity/validation").join(fixture);
    let project = fs::read(&source).unwrap();
    let project_path = runner.work.join(source.file_name().unwrap());
    fs::write(&project_path, &project).unwrap();
    let output_dir = runner.work.join("native");
    fs::create_dir(&output_dir).unwrap();
    let case = runner
        .slice_case(&ExportedCase {
            label: format!("validation/exclude-outline/{fixture}"),
            project: project.clone(),
            project_path,
            output_dir,
        })
        .unwrap();
    let actual = slice_project_plate(
        project,
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    fs::write(runner.work.join("ares.gcode"), &actual).unwrap();
    fs::write(runner.work.join("orca.gcode"), &case.reference).unwrap();
    let actual = std::str::from_utf8(&actual).unwrap();
    let expected = std::str::from_utf8(&case.reference).unwrap();
    let actual_lines = normalize(actual);
    let expected_lines = normalize(expected);
    let first_difference = actual_lines
        .iter()
        .zip(&expected_lines)
        .position(|(actual, expected)| actual != expected)
        .or_else(|| {
            (actual_lines.len() != expected_lines.len())
                .then_some(actual_lines.len().min(expected_lines.len()))
        });
    fs::write(
        runner.work.join("exclude-outline-comparison.json"),
        serde_json::to_vec_pretty(&serde_json::json!({
            "fixture": fixture,
            "input_sha256": cache_identity::raw_digest(&case.project),
            "ares_sha256": cache_identity::raw_digest(actual.as_bytes()),
            "native_sha256": cache_identity::raw_digest(&case.reference),
            "ares_lines": actual_lines.len(),
            "native_lines": expected_lines.len(),
            "first_difference_line": first_difference.map(|index| index + 1),
            "comparison": "ordered complete lines and line count; generated-by only",
            "artifacts": runner.work,
        }))
        .unwrap(),
    )
    .unwrap();
    for (index, (actual, expected)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        assert_eq!(
            actual,
            expected,
            "first mismatch at line {}; artifacts {:?}",
            index + 1,
            runner.work
        );
    }
    assert_eq!(
        actual_lines.len(),
        expected_lines.len(),
        "artifacts {:?}",
        runner.work
    );
}

fn normalize(text: &str) -> Vec<&str> {
    text.lines()
        .map(|line| {
            if line.starts_with("; generated by") {
                "; generated by"
            } else {
                line
            }
        })
        .collect()
}

#[tokio::test]
async fn rotation_residue_hull_keeps_edge_midpoints_like_native() {
    check("exclude-outline-jitter.3mf").await;
}

#[tokio::test]
async fn identity_transform_hull_stays_four_corners() {
    check("exclude-outline-identity.3mf").await;
}
