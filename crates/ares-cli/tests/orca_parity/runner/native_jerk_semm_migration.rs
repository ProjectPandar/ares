//! Runtime Native whole-stream comparisons; no committed Native output.
//! Role jerk: ExtrusionEntity.hpp:63-83, GCode.cpp:6440-6462,
//! GCodeWriter.cpp:255-341. SEMM M104: GCode.cpp:7998-8004,
//! GCodeWriter.cpp:159-164. See native-artifact-cleanup-jerk-semm-spec.md.
//! Keep the original generated-only normalization, ordered lines and length;
//! retain inputs/configuration and check role/temperature controls on both streams.
//! OrcaRunner owns required/optional dependency policy and slice_case caching.

use super::{
    ExportedCase, OrcaRunner, application::slice_project_plate, cache_identity, repo_root,
};
use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext};
use std::fs;

async fn check(fixture: &str, controls: fn(&str)) {
    let Some(runner) = OrcaRunner::from_env().unwrap() else {
        return;
    };
    let source = repo_root().join("tests/parity/validation").join(fixture);
    let project = fs::read(&source).unwrap();
    let input = runner.work.join(source.file_name().unwrap());
    fs::write(&input, &project).unwrap();
    let output_dir = runner.work.join("native");
    fs::create_dir(&output_dir).unwrap();
    let case = runner
        .slice_case(&ExportedCase {
            label: format!("validation/jerk-semm/{fixture}"),
            project: project.clone(),
            project_path: input,
            output_dir,
        })
        .unwrap();
    let actual = slice_project_plate(
        project,
        GenerationMetadata::default(),
        None,
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    fs::write(runner.work.join("ares.gcode"), &actual).unwrap();
    fs::write(runner.work.join("orca.gcode"), &case.reference).unwrap();
    let actual = std::str::from_utf8(&actual).unwrap();
    let expected = std::str::from_utf8(&case.reference).unwrap();
    let actual_lines = normalize(actual);
    let expected_lines = normalize(expected);
    let first_difference = actual_lines
        .iter()
        .zip(&expected_lines)
        .position(|(actual, expected)| actual != expected)
        .or_else(|| {
            (actual_lines.len() != expected_lines.len())
                .then_some(actual_lines.len().min(expected_lines.len()))
        });
    fs::write(
        runner.work.join("jerk-semm-comparison.json"),
        serde_json::to_vec_pretty(&serde_json::json!({
            "fixture": fixture,
            "input_sha256": cache_identity::raw_digest(&case.project),
            "ares_sha256": cache_identity::raw_digest(actual.as_bytes()),
            "native_sha256": cache_identity::raw_digest(&case.reference),
            "ares_lines": actual_lines.len(),
            "native_lines": expected_lines.len(),
            "first_difference_line": first_difference.map(|index| index + 1),
            "comparison": "ordered complete lines and line count; generated-by only",
            "artifacts": runner.work,
        }))
        .unwrap(),
    )
    .unwrap();
    for (index, (actual, expected)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        assert_eq!(
            actual,
            expected,
            "first mismatch at line {}; artifacts {:?}",
            index + 1,
            runner.work
        );
    }
    assert_eq!(
        actual_lines.len(),
        expected_lines.len(),
        "artifacts {:?}",
        runner.work
    );
    controls(expected);
    controls(actual);
}

fn normalize(text: &str) -> Vec<&str> {
    text.lines()
        .map(|line| {
            if line.starts_with("; generated by") {
                "; generated by"
            } else {
                line
            }
        })
        .collect()
}

fn overhang_jerk(text: &str) {
    let mut jerk = None;
    let mut overhangs = 0;
    for line in text.lines() {
        if let Some(parameters) = line.strip_prefix("M205 ") {
            jerk = parameters
                .split_whitespace()
                .find_map(|parameter| parameter.strip_prefix('X'));
        }
        if line == ";TYPE:Overhang wall" {
            assert_eq!(jerk, Some("9"), "overhang must use default jerk");
            overhangs += 1;
        }
    }
    assert!(overhangs > 0, "overhang role must be exercised");
}

fn klipper_jerk(text: &str) {
    let mut jerk = None;
    let mut previous_role = "";
    let mut gaps = 0;
    let mut transitions = 0;
    for line in text.lines() {
        if let Some(parameters) = line.strip_prefix("SET_VELOCITY_LIMIT ")
            && let Some(value) = parameters
                .split_whitespace()
                .find_map(|parameter| parameter.strip_prefix("SQUARE_CORNER_VELOCITY="))
        {
            jerk = Some(value);
        }
        if let Some(role) = line.strip_prefix(";TYPE:") {
            if role == "Gap infill" {
                assert_eq!(jerk, Some("9"), "gap fill must use default jerk");
                gaps += 1;
            }
            if previous_role == "Gap infill" {
                assert_eq!(role, "Internal solid infill");
                assert_eq!(jerk, Some("20"), "infill must restore infill jerk");
                transitions += 1;
            }
            previous_role = role;
        }
    }
    assert!(gaps > 0 && transitions > 0, "gap/infill switch must occur");
}

fn semm_temperatures(text: &str) {
    let commands: Vec<_> = text
        .lines()
        .filter(|line| line.starts_with("M104 "))
        .map(|line| line.split(';').next().unwrap().trim())
        .collect();
    assert_eq!(
        commands.iter().filter(|&&line| line == "M104 S220").count(),
        1
    );
    assert_eq!(
        commands.iter().filter(|&&line| line == "M104 S210").count(),
        75
    );
    assert!(commands.iter().all(|line| {
        !line
            .split_whitespace()
            .any(|parameter| parameter.starts_with('T'))
    }));
}

#[tokio::test]
async fn overhang_wall_jerk_matches_native() {
    check("overhang-jerk/project.3mf", overhang_jerk).await;
}

#[tokio::test]
async fn e5max_klipper_jerk_switches_match_native() {
    check("e5max-scv/project.3mf", klipper_jerk).await;
}

#[tokio::test]
async fn semm_toolchange_m104_matches_native() {
    check("semm-m104-k3m.3mf", semm_temperatures).await;
}
