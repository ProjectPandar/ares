//! Failure inventory: pause relocation changes move order, drops a suffix vertex,
//! remaps an ID incorrectly, or changes any exported processor field.
use super::{settings, slice, strict};
use crate::runner::OrcaRunner;
use ares_core::gcode_processor::process_gcode;
use std::{
    fs,
    io::{BufRead, BufReader, BufWriter, Write},
    path::Path,
};

const PROJECT: &[u8] = include_bytes!("../../../../../../tests/processor_seam_cache/anchor.3mf");

fn canonical_csv(source: &Path, target: &Path, floats: std::ops::RangeInclusive<usize>) {
    let mut output = BufWriter::new(fs::File::create(target).unwrap());
    for line in BufReader::new(fs::File::open(source).unwrap())
        .lines()
        .skip(1)
    {
        for (index, field) in line.unwrap().split(',').enumerate() {
            let bits = if floats.contains(&index) {
                field.parse::<f32>().unwrap().to_bits()
            } else {
                field.parse::<u32>().unwrap()
            };
            output.write_all(&bits.to_le_bytes()).unwrap();
        }
    }
}

#[test]
fn pause_relocation_preserves_a_long_extrusion_sequence() {
    let Some(oracle) = crate::native_environment::binary("ARES_PROCGCODE_BIN") else {
        return;
    };
    let Some(runner) = OrcaRunner::from_env().unwrap() else {
        return;
    };
    let reference = slice(&runner, PROJECT);
    let reference = std::str::from_utf8(&reference).unwrap();
    let mut input = String::from("; generated by OrcaSlicer 2.5.0\nG90\nM83\n");
    // Dummy + prefix places the pause at index 1,048,575: k=1.
    // OptionsZ push-then-erase shifts the copy from 1,048,576 to that index.
    for _ in 0..1_048_574 {
        input.push_str("G1 E1 F60\n");
    }
    input.push_str("M400\n;PAUSE_PRINT\n;TYPE:External perimeter\n;HEIGHT:0.2\n;WIDTH:0.4\nG1 X1 Z0.2 E0.1 F60\nM400\n");
    input.push_str("; CONFIG_BLOCK_START\n");
    input.push_str(
        reference
            .split_once("; CONFIG_BLOCK_START\n")
            .unwrap()
            .1
            .split_once("; CONFIG_BLOCK_END")
            .unwrap()
            .0,
    );
    input.push_str("; CONFIG_BLOCK_END\n");
    let path = runner.work.join("sequence.gcode");
    let native_csv = runner.work.join("native-moves.csv");
    let native_dynamics = runner.work.join("native-dynamics.csv");
    fs::write(&path, &input).unwrap();
    let started = std::time::Instant::now();
    let native = std::process::Command::new(&oracle)
        .arg("--process-gcode")
        .arg(&path)
        .arg("--dump-moves")
        .arg(&native_csv)
        .arg("--dump-move-dynamics")
        .arg(&native_dynamics)
        .output()
        .unwrap();
    fs::write(runner.work.join("native.stdout"), &native.stdout).unwrap();
    fs::write(runner.work.join("native.stderr"), &native.stderr).unwrap();
    assert!(
        native.status.success(),
        "Native {:?} at {:?}",
        native.status,
        runner.work
    );
    let native_gcode = fs::read(&path).unwrap();
    let actual = process_gcode(&input, &settings(reference), false, false);
    strict(&runner, &input, &native_gcode, &actual.gcode);
    let actual_csv = runner.work.join("ares-moves.csv");
    let mut csv = BufWriter::new(fs::File::create(&actual_csv).unwrap());
    writeln!(csv, "gcode_id,type,role,extruder_id,color,x,y,z,delta,feedrate,width,height,mm3,travel,fan,temp,time,layer,internal").unwrap();
    let actual_dynamics = runner.work.join("ares-dynamics.csv");
    let mut dynamics = BufWriter::new(fs::File::create(&actual_dynamics).unwrap());
    writeln!(
        dynamics,
        "gcode_id,type,internal,pa,acceleration,jerk,actual_feedrate"
    )
    .unwrap();
    for v in &actual.result.moves {
        let [x, y, z] = v.position;
        writeln!(
            csv,
            "{},{},{},{},{},{x},{y},{z},{},{},{},{},{},{},{},{},{},{},{}",
            v.gcode_id,
            v.move_type as u8,
            v.extrusion_role as u8,
            v.extruder_id,
            v.cp_color_id,
            v.delta_extruder,
            v.feedrate,
            v.width,
            v.height,
            v.mm3_per_mm,
            v.travel_dist,
            v.fan_speed,
            v.temperature,
            v.time,
            v.layer_id,
            u8::from(v.internal_only)
        )
        .unwrap();
        writeln!(
            dynamics,
            "{},{},{},{},{},{},{}",
            v.gcode_id,
            v.move_type as u8,
            u8::from(v.internal_only),
            v.pressure_advance,
            v.acceleration,
            v.jerk,
            v.actual_feedrate
        )
        .unwrap();
    }
    drop(csv);
    drop(dynamics);
    for (label, native, actual, float_columns) in [
        ("moves", native_csv, actual_csv, 5..=16),
        ("dynamics", native_dynamics, actual_dynamics, 3..=6),
    ] {
        let expected = runner.work.join(format!("native-{label}.bin"));
        let observed = runner.work.join(format!("ares-{label}.bin"));
        canonical_csv(&native, &expected, float_columns.clone());
        canonical_csv(&actual, &observed, float_columns);
        let expected = fs::read(&expected).unwrap();
        let observed = fs::read(&observed).unwrap();
        assert!(
            expected == observed,
            "complete {label} bytes differ at {:?}; {:?}",
            expected.iter().zip(&observed).position(|(a, b)| a != b),
            runner.work
        );
    }
    fs::write(
        runner.work.join("elapsed.txt"),
        format!("{} seconds\n", started.elapsed().as_secs_f64()),
    )
    .unwrap();
}
