//! Exercise the real reference retry entrypoint without a live Orca dependency.
#![cfg(unix)]

use std::{fs, os::unix::fs::PermissionsExt, process::Command};

use super::{ExportedCase, OrcaRunner};

#[test]
fn reordered_reference_cannot_pass_via_line_multiset_envelope() {
    run_case("reordered");
}

#[test]
fn exact_reference_passes_without_retry() {
    run_case("exact");
}

#[test]
fn exact_reference_on_retry_passes() {
    run_case("eventual");
}

fn run_case(mode: &str) {
    let temp = tempfile::tempdir().unwrap();
    fs::create_dir(temp.path().join("resources")).unwrap();
    let output = Command::new(std::env::current_exe().unwrap())
        .args([
            "--exact",
            "runner::strict_reference_tests::reordered_reference_child",
            "--nocapture",
        ])
        .env("ARES_STRICT_REFERENCE_CHILD", temp.path())
        .env("ARES_STRICT_REFERENCE_MODE", mode)
        .env("ARES_PARITY_ARTIFACT_ROOT", temp.path())
        .env("ARES_ORCA_RUNS", "2")
        .env("ARES_ORCA_NATIVE_BIN", temp.path().join("oracle.sh"))
        .env("ARES_ORCA_RESOURCES_DIR", temp.path().join("resources"))
        .output()
        .unwrap();
    assert!(
        String::from_utf8_lossy(&output.stdout)
            .lines()
            .any(|line| line == "running 1 test"),
        "child selector did not run exactly one test: {output:?}"
    );
    assert!(
        output.status.success(),
        "{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

#[test]
fn reordered_reference_child() {
    let Some(root) = std::env::var_os("ARES_STRICT_REFERENCE_CHILD") else {
        return;
    };
    let root = std::path::PathBuf::from(root);
    let project =
        fs::read(super::repo_root().join("tests/parity/replay/ender3-classic.3mf")).unwrap();
    let runtime = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap();
    let ares = runtime
        .block_on(crate::runner::application::slice_project(
            &project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();
    let text = String::from_utf8(ares.clone()).unwrap().replace(
        "; generated by Ares 2.5.0-beta\n",
        "; generated by OrcaSlicer 2.5.0-beta on 2026-08-27 at 00:00:00\n",
    );
    let mut lines = text.lines().collect::<Vec<_>>();
    let first = lines
        .iter()
        .position(|line| line.starts_with("G1 "))
        .unwrap();
    let second = lines[first + 1..]
        .iter()
        .position(|line| line.starts_with("G1 "))
        .unwrap()
        + first
        + 1;
    lines.swap(first, second);
    let reordered = format!("{}\n", lines.join("\n"));
    assert!(
        crate::golden::compare_ordered_bytes_generator_only(reordered.as_bytes(), &ares).is_err()
    );
    lines.sort_unstable();
    let mut original_lines = text.lines().collect::<Vec<_>>();
    original_lines.sort_unstable();
    assert_eq!(lines, original_lines);
    let mode = std::env::var("ARES_STRICT_REFERENCE_MODE").unwrap();
    let final_reference = if mode == "reordered" {
        &reordered
    } else {
        &text
    };
    fs::write(
        root.join("first.gcode"),
        if mode == "exact" { &text } else { &reordered },
    )
    .unwrap();
    fs::write(root.join("reference.gcode"), final_reference).unwrap();
    let bin = root.join("oracle.sh");
    fs::write(
        &bin,
        "#!/bin/sh\nset -e\nwhile [ \"$#\" -gt 0 ]; do\n  case \"$1\" in\n    --outputdir) output=$2; shift 2 ;;\n    *) shift ;;\n  esac\ndone\nif [ -f calls ]; then cp reference.gcode \"$output/plate_1.gcode\"; else cp first.gcode \"$output/plate_1.gcode\"; fi\nprintf x >> calls\n",
    )
    .unwrap();
    fs::set_permissions(&bin, fs::Permissions::from_mode(0o755)).unwrap();
    let output_dir = root.join("output");
    fs::create_dir(&output_dir).unwrap();
    let project_path = root.join("input.3mf");
    fs::write(&project_path, &project).unwrap();
    let exported = ExportedCase {
        label: "reordered-reference".into(),
        project,
        project_path,
        output_dir,
    };
    let runner = OrcaRunner {
        bin,
        work: root.clone(),
        cache: root.clone(),
        producer: Default::default(),
    };
    let outcome = crate::compare_exported_for(&runner, &exported, None);
    assert_eq!(
        outcome.status,
        if mode == "reordered" {
            "DIVERGENT"
        } else {
            "PASS"
        },
        "{}",
        outcome.detail
    );
    assert_eq!(
        fs::read(root.join("calls")).unwrap(),
        if mode == "exact" {
            b"x".as_slice()
        } else {
            b"xx".as_slice()
        }
    );
    let artifacts = outcome.artifacts.unwrap();
    assert_eq!(
        fs::read(artifacts.join("orca.gcode")).unwrap(),
        final_reference.as_bytes()
    );
    assert_eq!(fs::read(artifacts.join("ares.gcode")).unwrap(), ares);
}
