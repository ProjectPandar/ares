pub(super) fn check_native_processor(output: &ares_core::ProcessedGCode, name: &str) {
    let Some(_) = crate::native_environment::binary("ARES_PROCGCODE_BIN") else {
        return;
    };
    let Some(runner) = crate::runner::OrcaRunner::from_env().unwrap() else {
        return;
    };
    let directory = &runner.work;
    let gcode = directory.join("input.gcode");
    std::fs::write(directory.join("scenario.txt"), name).unwrap();
    std::fs::write(&gcode, &output.gcode).unwrap();
    // Match the existing gcode_moves_oracle producer-only normalization:
    // process_file loads embedded printer config only for known producers
    // (GCodeProcessor.cpp:2620-2633). Keep all G-code commands/line ids intact.
    let text = std::str::from_utf8(&output.gcode).unwrap();
    let renamed = text.replacen(
        "\n; generated by Ares 2.5.0\n",
        "\n; generated by OrcaSlicer 2.5.0\n",
        1,
    );
    assert_ne!(renamed, text);
    let oracle_input = directory.join("oracle-input.gcode");
    std::fs::write(&oracle_input, renamed).unwrap();
    let raw = runner
        .processor_raw_color_reference(&oracle_input)
        .unwrap()
        .unwrap();
    let native_json = raw.join("native.json");
    let native_csv = raw.join("native.csv");
    let native: serde_json::Value =
        serde_json::from_slice(&std::fs::read(native_json).unwrap()).unwrap();
    std::fs::write(
        directory.join("oracle-identities.json"),
        serde_json::to_vec_pretty(&serde_json::json!({
            "raw":std::env::var_os("ARES_PROCGCODE_BIN"),
        }))
        .unwrap(),
    )
    .unwrap();
    let expected: Vec<f64> =
        serde_json::from_value(native["volumes_per_color_change"].clone()).unwrap();
    std::fs::write(
        directory.join("rust-statistics.json"),
        serde_json::to_vec_pretty(&output.result.print_statistics).unwrap(),
    )
    .unwrap();
    let expected_z: Vec<f64> = native["custom_gcode_per_print_z"]
        .as_array()
        .unwrap()
        .iter()
        .map(|item| item["print_z"].as_f64().unwrap())
        .collect();
    assert_eq!(
        output
            .result
            .custom_gcode_per_print_z
            .iter()
            .map(|item| item.print_z)
            .collect::<Vec<_>>(),
        expected_z
    );
    let raw_xyz = xyz_bits(&native_csv);
    let rust_xyz: Vec<_> = output
        .result
        .moves
        .iter()
        .map(|v| v.position.map(f32::to_bits))
        .collect();
    assert_eq!(rust_xyz.len(), raw_xyz.len(), "full vertex count");
    // Beta upstreamed the marker-index correction
    // (`OptionsZCorrector::on_moves_inserted`, GCodeProcessor.hpp:1105-1116,
    // called at GCodeProcessor.cpp:8132), so raw Native beta is the complete
    // authority: Ares must match it bit for bit, not differ like a patch.
    let raw_rust_diff = xyz_diff(&raw_xyz, &rust_xyz);
    std::fs::write(
        directory.join("raw-to-rust-xyz-bits-diff.json"),
        serde_json::to_vec_pretty(&raw_rust_diff).unwrap(),
    )
    .unwrap();
    assert!(
        raw_rust_diff.is_empty(),
        "Ares XYZ must be bit-identical to raw Native beta"
    );
    let expected_moves: Vec<_> = std::fs::read_to_string(&native_csv)
        .unwrap()
        .lines()
        .skip(1)
        .filter_map(|line| {
            let fields: Vec<_> = line.split(',').collect();
            (fields[1] == "10").then(|| {
                (
                    fields[0].parse::<u32>().unwrap(),
                    fields[4].parse::<u8>().unwrap(),
                )
            })
        })
        .collect();
    let actual_moves: Vec<_> = output
        .result
        .moves
        .iter()
        .filter(|vertex| vertex.move_type == ares_core::gcode_processor::EMoveType::Extrude)
        .map(|vertex| (vertex.gcode_id, vertex.cp_color_id))
        .collect();
    std::fs::write(
        directory.join("rust-move-identities.json"),
        serde_json::to_vec_pretty(
            &output
                .result
                .moves
                .iter()
                .map(|v| {
                    serde_json::json!({
                        "line":v.gcode_id, "color":v.cp_color_id, "type":v.move_type as u8,
                        "internal":v.internal_only, "position":v.position, "time":v.time,
                    })
                })
                .collect::<Vec<_>>(),
        )
        .unwrap(),
    )
    .unwrap();
    assert_eq!(
        actual_moves.len(),
        expected_moves.len(),
        "extrusion vertex count"
    );
    for (index, (actual, expected)) in actual_moves.iter().zip(&expected_moves).enumerate() {
        assert_eq!(actual, expected, "extrusion vertex {index}");
    }
    let expected_items = native["custom_gcode_per_print_z"].as_array().unwrap();
    assert_eq!(
        output.result.custom_gcode_per_print_z.len(),
        expected_items.len()
    );
    for (actual, expected) in output
        .result
        .custom_gcode_per_print_z
        .iter()
        .zip(expected_items)
    {
        assert_eq!(actual.kind as u64, expected["type"].as_u64().unwrap());
        assert_eq!(
            u64::from(actual.extruder),
            expected["extruder"].as_u64().unwrap()
        );
        assert_eq!(actual.color, expected["color"].as_str().unwrap());
    }
    let expected_times = native["custom_gcode_times"].as_array().unwrap();
    assert_eq!(output.result.custom_gcode_times.len(), expected_times.len());
    for (actual, expected) in output.result.custom_gcode_times.iter().zip(expected_times) {
        assert_eq!(actual.kind as u64, expected["type"].as_u64().unwrap());
        // Native fields are float (GCodeProcessor.hpp:505). Compare those
        // bits, not extra f64 precision introduced by JSON decimal parsing.
        assert_eq!(
            actual.duration.to_bits(),
            (expected["duration"].as_f64().unwrap() as f32).to_bits()
        );
        assert_eq!(
            actual.remaining.to_bits(),
            (expected["remaining"].as_f64().unwrap() as f32).to_bits()
        );
    }
    std::fs::write(
        directory.join("rust-custom-times.json"),
        serde_json::to_vec_pretty(&output.result.custom_gcode_times).unwrap(),
    )
    .unwrap();
    // Both processors accumulate the same per-G1 float volume into a double
    // cache; compare raw volumes, not reconstructed metric legend strings.
    assert_eq!(
        output.result.print_statistics.volumes_per_color_change,
        expected
    );
}

fn xyz_bits(path: &std::path::Path) -> Vec<[u32; 3]> {
    std::fs::read_to_string(path)
        .unwrap()
        .lines()
        .skip(1)
        .map(|line| {
            let fields: Vec<_> = line.split(',').collect();
            std::array::from_fn(|axis| fields[5 + axis].parse::<f32>().unwrap().to_bits())
        })
        .collect()
}

// Include absent tail vertices as None, rather than truncating a zip. Each
// tuple is (ordinal, raw XYZ bits, other XYZ bits); signed zero is preserved.
type XyzDifference = (usize, Option<[u32; 3]>, Option<[u32; 3]>);

fn xyz_diff(raw: &[[u32; 3]], other: &[[u32; 3]]) -> Vec<XyzDifference> {
    (0..raw.len().max(other.len()))
        .filter_map(|ordinal| {
            let before = raw.get(ordinal).copied();
            let after = other.get(ordinal).copied();
            (before != after).then_some((ordinal, before, after))
        })
        .collect()
}
