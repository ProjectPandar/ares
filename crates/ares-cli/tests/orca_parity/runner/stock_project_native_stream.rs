use super::{ExportedCase, cache_identity, repo_root};
use assert_cmd::assert::OutputAssertExt;
use std::{fs, path::Path};

fn compare(reference: &[u8], actual: &[u8], artifacts: &Path) -> Result<(), String> {
    crate::golden::compare_ordered_bytes_generator_only(reference, actual)
        .map_err(|error| format!("{error}; complete artifacts {artifacts:?}"))
}

#[test]
fn project_matches_initialized_orca_ordered_bytes() {
    let Some(runner) = producer::runner(
        "runner::stock_project_native_stream::project_matches_initialized_orca_ordered_bytes",
    ) else {
        return;
    };
    let source = repo_root().join("tests/ksr_fdmtest_v4/ksr_fdmtest_v4.project.3mf");
    let project = fs::read(&source).unwrap();
    assert_eq!(
        cache_identity::raw_digest(&project),
        "698f40f13c9075b818abedd3d10f022fbb5d8200aed48fbdde651f6bfb21b8a9",
        "{:?}",
        runner.work
    );
    let project_path = runner.work.join(source.file_name().unwrap());
    fs::write(&project_path, &project).unwrap();
    let output_dir = runner.work.join("native");
    fs::create_dir(&output_dir).unwrap();
    let case = runner
        .slice_case(&ExportedCase {
            label: "ksr/initialized".to_owned(),
            project,
            project_path: project_path.clone(),
            output_dir,
        })
        .unwrap();
    fs::write(runner.work.join("orca.gcode"), &case.reference).unwrap();
    let output = runner.work.join("ares.gcode");
    crate::runner::application::cli_command()
        .args([
            "slice",
            "-o",
            output.to_str().unwrap(),
            project_path.to_str().unwrap(),
        ])
        .output()
        .unwrap()
        .assert()
        .success();
    let actual = fs::read(output).unwrap();
    compare(&case.reference, &actual, &runner.work).unwrap();
    assert_eq!(
        std::str::from_utf8(&actual)
            .unwrap()
            .lines()
            .find(|line| line.starts_with("; generated by OrcaSlicer (Ares ")),
        Some(concat!(
            "; generated by OrcaSlicer (Ares ",
            env!("CARGO_PKG_VERSION"),
            ") on 1980-01-01 at 00:00:00"
        ))
    );
    let changed_id = String::from_utf8(actual)
        .unwrap()
        .replace(" id:0 copy 0", " id:1 copy 0");
    fs::write(runner.work.join("changed-id.gcode"), &changed_id).unwrap();
    let error = compare(&case.reference, changed_id.as_bytes(), &runner.work).unwrap_err();
    assert!(error.contains("first difference at byte"), "{error}");
}
