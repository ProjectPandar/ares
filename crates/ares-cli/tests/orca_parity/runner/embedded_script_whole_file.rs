//! The embedded-script receipt case upgraded to whole-file comparison (the
//! chain exit criterion's last case): Ender-3 3MF + BBL X1C catalog with a
//! user process, sliced by Ares through the catalog request and by the
//! oracle with the same `--load-settings`/`--load-filaments` flags. The
//! loaded machine's bed (256×256) is larger than the embedded bed (220×220),
//! so upstream re-centers every instance and the wipe tower onto the new bed
//! (`OrcaSlicer.cpp:3766-3796` classification, `:3958-4053`
//! translate_models); the whole sliced output compares byte-for-byte after
//! normalizing only the `; generated by` banner.

use ares_core::{ConfigOverrides, Placement, ProfileSliceRequest};
use serde_json::{Value, json};

use super::{
    OrcaRunner,
    profile_entry::{vendor, write_json},
    stages,
};
use crate::presets::VendorProfiles;

fn normalized(gcode: &str) -> String {
    gcode
        .lines()
        .filter(|line| !line.starts_with("; generated by "))
        .collect::<Vec<_>>()
        .join("\n")
}

fn first_difference(expected: &str, actual: &str) -> String {
    for (index, (expected_line, actual_line)) in expected.lines().zip(actual.lines()).enumerate() {
        if expected_line != actual_line {
            return format!(
                "line {}: native {expected_line:?} != ares {actual_line:?}",
                index + 1
            );
        }
    }
    let noun = if expected.lines().count() == actual.lines().count() {
        "content"
    } else {
        "line count"
    };
    format!(
        "{noun}: native has {} lines, ares has {}",
        expected.lines().count(),
        actual.lines().count()
    )
}

#[tokio::test]
async fn orca_parity_embedded_script_whole_file_matches_native() {
    let root = super::repo_root();
    let profiles_root = root.join("OrcaSlicer/resources/profiles");
    let profiles = VendorProfiles::load(&profiles_root, "BBL").unwrap();
    let machine = "Bambu Lab X1 Carbon 0.4 nozzle";
    let system_process = "0.20mm Standard @BBL X1C";
    let process = "0.20mm Standard @BBL X1C - Mine";
    let filament = "Bambu PLA Basic @BBL X1C";
    let catalog = json!({
        "vendors": [vendor(&profiles_root, "OrcaFilamentLibrary"), vendor(&profiles_root, "BBL")],
        "imports": [{
            "profiles": [{
                "type": "process",
                "name": process,
                "from": "user",
                "inherits": system_process,
                "instantiation": "true",
            }],
        }],
    });
    let selection = json!({"machine": machine, "process": process, "filaments": [filament]});
    let directory = tempfile::Builder::new()
        .prefix("embedded-script-whole-file-")
        .tempdir()
        .unwrap()
        .keep();
    write_json(&directory.join("catalog.json"), &catalog);
    write_json(&directory.join("selection.json"), &selection);
    let mut process_fields = profiles.process(system_process).unwrap();
    process_fields.insert("name".to_owned(), Value::String(process.to_owned()));
    process_fields.insert("from".to_owned(), Value::String("user".to_owned()));
    process_fields.insert(
        "inherits".to_owned(),
        Value::String(system_process.to_owned()),
    );
    for (kind, fields) in [
        ("machine", profiles.machine(machine).unwrap()),
        ("process", process_fields),
        ("filament", profiles.filament(filament).unwrap()),
    ] {
        write_json(
            &directory.join(format!("{kind}.json")),
            &Value::Object(fields),
        );
    }
    let input = include_bytes!("../../../../../tests/parity/validation/preset-json-ender3-0.2.3mf");
    std::fs::write(directory.join("input.3mf"), input).unwrap();
    let catalog_json = catalog.to_string();
    let selection_json = selection.to_string();
    let overrides = ConfigOverrides::default();
    let request = ProfileSliceRequest {
        filename: "input.3mf",
        catalog_json: &catalog_json,
        selection_json: &selection_json,
        plate: None,
        overrides: &overrides,
        placement: Placement::None,
    };
    let ares = ares_core::slice_with_profiles(
        input,
        request,
        ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
        ares_core::SlicerContext::new(0),
    )
    .await
    .unwrap();
    let Some(runner) = OrcaRunner::from_env().unwrap() else {
        return;
    };
    let path = |file: &str| directory.join(file).to_str().unwrap().to_owned();
    let output = directory.join("native");
    std::fs::create_dir(&output).unwrap();
    stages::run(
        runner.bin(),
        [
            "--load-settings".to_owned(),
            format!("{};{}", path("machine.json"), path("process.json")),
            "--load-filaments".to_owned(),
            path("filament.json"),
            "--slice".to_owned(),
            "0".to_owned(),
            "--outputdir".to_owned(),
            output.to_str().unwrap().to_owned(),
            path("input.3mf"),
        ],
        stages::Stage::Slice,
        &directory,
    )
    .unwrap();
    let native = std::fs::read_to_string(output.join("plate_1.gcode")).unwrap();
    let ares = String::from_utf8_lossy(&ares).into_owned();
    let (native_normalized, ares_normalized) = (normalized(&native), normalized(&ares));
    assert_eq!(
        native_normalized,
        ares_normalized,
        "embedded-script case must match native byte-for-byte (only the banner normalized): {}",
        first_difference(&native_normalized, &ares_normalized)
    );
}
