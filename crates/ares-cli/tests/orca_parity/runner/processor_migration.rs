#[test]
fn generator_only_requires_exact_final_release_for_each_producer() {
    for (brand, header) in [
        (
            "OrcaSlicer",
            "; generated by OrcaSlicer 2.5.0 on 2026-09-08 at 04:26:03\n",
        ),
        (
            "Ares",
            "; generated by Ares 2.5.0 on 1980-01-01 at 00:00:00\n",
        ),
    ] {
        let body = "; generated by Vendor 9.1 on 2026-09-08 at 04:26:03\nG1 X1\n";
        let valid = format!("{header}{body}");
        assert_eq!(
            generator_only(valid.as_bytes(), brand),
            format!("; generated by <SLICER> 2.5.0\n{body}").as_bytes()
        );
        for invalid in [
            valid.replace("2.5.0", "2.5.0-beta"),
            valid.replace("2.5.0", "2.5.0-rc"),
            valid.replace("2.5.0", "2x5x0"),
            format!("{header}{valid}"),
            body.to_owned(),
        ] {
            assert!(
                std::panic::catch_unwind(|| generator_only(invalid.as_bytes(), brand)).is_err()
            );
        }
    }
}

