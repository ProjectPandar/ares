use super::{ExportedCase, OrcaRunner, cache_identity, repo_root};
use ares_core::{ConfigOverrides, GenerationMetadata, SlicerContext, slice_project_plate};
use std::fs;

#[tokio::test]
async fn plate_two_min_slices_like_native() {
    let Some(runner) = OrcaRunner::from_env().unwrap() else {
        return;
    };
    let source = repo_root().join("tests/parity/validation/print-bed-two-plates-min.3mf");
    let project = fs::read(&source).unwrap();
    let project_path = runner.work.join(source.file_name().unwrap());
    fs::write(&project_path, &project).unwrap();
    let output_dir = runner.work.join("native");
    fs::create_dir(&output_dir).unwrap();
    let case = runner
        .slice_selected_plate_case(
            &ExportedCase {
                label: "validation/o6/plate-2".to_owned(),
                project: project.clone(),
                project_path,
                output_dir,
            },
            2,
        )
        .unwrap();
    let gcode = slice_project_plate(
        project,
        GenerationMetadata::default(),
        Some(2),
        &ConfigOverrides::default(),
        SlicerContext::new(0),
    )
    .await
    .unwrap();
    fs::write(runner.work.join("ares.gcode"), &gcode).unwrap();
    fs::write(runner.work.join("orca.gcode"), &case.reference).unwrap();
    fs::write(
        runner.work.join("plate-origin-comparison.json"),
        serde_json::to_vec_pretty(&serde_json::json!({
            "fixture": source,
            "plate": 2,
            "input_sha256": cache_identity::raw_digest(&case.project),
            "ares_sha256": cache_identity::raw_digest(&gcode),
            "native_sha256": cache_identity::raw_digest(&case.reference),
            "ares_lines": std::str::from_utf8(&gcode).unwrap().lines().count(),
            "native_lines": std::str::from_utf8(&case.reference).unwrap().lines().count(),
            "artifacts": runner.work,
        }))
        .unwrap(),
    )
    .unwrap();
    assert_matches_native(&gcode, &case.reference);
}

fn normalize(text: &str) -> Vec<&str> {
    fn normalize_line(line: &str) -> &str {
        if line.starts_with("; generated by") {
            "; generated by"
        } else {
            line
        }
    }
    text.lines().map(normalize_line).collect()
}

fn assert_matches_native(actual: &[u8], expected: &[u8]) {
    let actual = String::from_utf8(actual.to_vec()).unwrap();
    let expected = String::from_utf8(expected.to_vec()).unwrap();
    let actual_lines = normalize(&actual);
    let expected_lines = normalize(&expected);
    for (index, (actual, expected)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        assert_eq!(actual, expected, "first mismatch at line {}", index + 1);
    }
    assert_eq!(actual_lines.len(), expected_lines.len());
}
