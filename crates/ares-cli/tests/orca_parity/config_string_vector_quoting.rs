//! `escape_strings_cstyle` (`Config.cpp:98-131` at v2.5.0-beta `345efec64`) quotes a string-vector
//! element that holds a space, tab, semicolon, backslash, quote or line break. A collision-volume
//! definition `z_min..z_max;polygon` holds a semicolon, so the G-code config block writes it quoted,
//! and reading the config back keeps it one element.
//!
//! RED: Ares quoted on every one of those characters but the semicolon, so it wrote
//! `0..250;0x0,10x0,10x10,0x10` bare where Native writes it quoted.

use super::plater_archive::rewrite_archive;
use crate::runner::{OrcaRunner, repo_root};

const PROJECT: &str = "Metadata/project_settings.config";

fn normalized(bytes: &[u8]) -> Vec<String> {
    std::str::from_utf8(bytes)
        .unwrap()
        .lines()
        .map(|line| {
            if line.starts_with("; generated by") {
                "; generated by"
            } else {
                line
            }
        })
        .map(str::to_owned)
        .collect()
}

#[test]
fn config_block_quotes_a_string_vector_element_holding_a_semicolon_like_native() {
    let Some(runner) = OrcaRunner::from_env().unwrap() else {
        return;
    };
    // An Ender-3 volume list; in the default Shared mode it changes nothing but the config block.
    let input = rewrite_archive(
        &std::fs::read(repo_root().join("tests/parity/orca_cli_ender3.3mf")).unwrap(),
        |name, text| {
            (name == PROJECT).then(|| {
                assert!(text.starts_with('{'));
                text.replacen(
                    '{',
                    "{\n\t\"extruder_bed_exclude_volumes\": [\"0..250;0x0,10x0,10x10,0x10\"],",
                    1,
                )
            })
        },
    );
    let exported = runner
        .fixture_case("config-string-vector-quoting", input)
        .unwrap();
    let sliced = runner.slice_case(&exported).unwrap();
    let line = "; extruder_bed_exclude_volumes = \"0..250;0x0,10x0,10x10,0x10\"";
    assert!(
        normalized(&sliced.reference)
            .iter()
            .any(|text| text == line),
        "Native must write the volume quoted"
    );
    let actual = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap()
        .block_on(crate::runner::application::slice_project(
            &sliced.project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();
    assert_eq!(normalized(&actual), normalized(&sliced.reference));
}
