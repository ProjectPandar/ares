use std::io::{Cursor, Read, Write};

#[test]
fn btt_artifacts_compare_raw_bytes_and_reject_output_mutations() {
    let original =
        std::fs::read(crate::runner::repo_root().join("tests/parity/replay/ender3-classic.3mf"))
            .unwrap();
    let mut archive = zip::ZipArchive::new(Cursor::new(original)).unwrap();
    let mut output = zip::ZipWriter::new(Cursor::new(Vec::new()));
    for index in 0..archive.len() {
        let mut entry = archive.by_index(index).unwrap();
        let mut bytes = Vec::new();
        entry.read_to_end(&mut bytes).unwrap();
        if entry.name() == "Metadata/project_settings.config" {
            let mut settings: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
            settings["thumbnails"] = serde_json::json!("123x45/BTT_TFT");
            bytes = serde_json::to_vec(&settings).unwrap();
        }
        output
            .start_file(entry.name(), zip::write::SimpleFileOptions::DEFAULT)
            .unwrap();
        output.write_all(&bytes).unwrap();
    }
    let project = output.finish().unwrap().into_inner();
    let runtime = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap();
    let actual = runtime
        .block_on(crate::runner::application::slice_project(
            &project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();
    let text = std::str::from_utf8(&actual).unwrap();
    assert!(!text.contains("; HEADER_BLOCK_START"));
    assert!(!text.contains("; generated by"));
    let root = tempfile::tempdir().unwrap();
    // Synthetic comparator tests, not independent official-output evidence.
    let exact = super::compare(
        root.path(),
        "synthetic-btt-exact",
        Ok(&project),
        Ok(&actual),
        serde_json::json!({"kind":"synthetic-comparator-test"}),
    )
    .unwrap();
    assert_eq!(exact.status, "PASS", "{}", exact.detail);
    let manifest: serde_json::Value = serde_json::from_slice(
        &std::fs::read(exact.artifacts.unwrap().join("manifest.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(manifest["evidence"], "ordered_bytes_exact");
    assert_eq!(
        manifest["comparator"],
        "golden::first_difference (raw bytes)"
    );
    let mut reordered = text.split_inclusive('\n').collect::<Vec<_>>();
    let first = reordered
        .iter()
        .position(|line| line.starts_with("G1 "))
        .unwrap();
    let second = reordered
        .iter()
        .enumerate()
        .skip(first + 1)
        .find(|(_, line)| line.starts_with("G1 "))
        .unwrap()
        .0;
    reordered.swap(first, second);
    for changed in [
        format!("; HEADER_BLOCK_START\n{text}"),
        text.replacen("G1 X", "G1 X9", 1),
        reordered.concat(),
        format!("{text}\n"),
    ] {
        assert_ne!(changed.as_bytes(), actual);
        let result = super::compare(
            root.path(),
            "synthetic-btt-mutated",
            Ok(&project),
            Ok(changed.as_bytes()),
            serde_json::json!({"kind":"synthetic-comparator-test"}),
        )
        .unwrap();
        assert_eq!(result.status, "DIVERGENT", "{}", result.detail);
    }
}
