use std::fs::{self, File};
use std::io::Write;
use std::panic::{AssertUnwindSafe, catch_unwind};
use std::path::Path;

use md5::{Digest, Md5};
use zip::{ZipWriter, write::SimpleFileOptions};

use super::comparator::{Member, compare_members, read_members};

const OBJECT_A: &str = "3D/Objects/a_1.model";
const OBJECT_B: &str = "3D/Objects/b_2.model";
const CHECKSUM_A: &str = "Metadata/plate_1.gcode.md5";
const CHECKSUM_B: &str = "Metadata/plate_2.gcode.md5";
const GCODE_A: &str = "Metadata/plate_1.gcode";
const GCODE_B: &str = "Metadata/plate_2.gcode";
const BANNER: &[u8] = b"; generated by Slicer on 1980-01-01 at 00:00:00\n";

type Entries = Vec<(&'static str, Vec<u8>)>;

#[test]
fn sliced_archive_matches_object_permutations_within_their_span() {
    let reference = archive();
    let mut actual = reference.clone();
    swap(&mut actual, OBJECT_A, OBJECT_B);
    compare_archives(&reference, &actual);
}

#[test]
fn sliced_archive_matches_plate_gcode_permutations_within_their_span() {
    let reference = archive();
    let mut actual = reference.clone();
    swap(&mut actual, GCODE_A, GCODE_B);
    compare_archives(&reference, &actual);

    swap(&mut actual, OBJECT_A, OBJECT_B);
    let plate_b = index(&actual, GCODE_B);
    let checksum_b = index(&actual, CHECKSUM_B);
    actual[plate_b].1 = b"; generated by Ares on 2026-11-01 at 00:00:00\nG1 X20\n".to_vec();
    actual[checksum_b].1 = digest(&actual[plate_b].1);
    compare_archives(&reference, &actual);
}

#[test]
fn sliced_archive_requires_the_same_parallel_member_names_and_count() {
    let reference = archive();
    let mut missing = reference.clone();
    missing.remove(index(&missing, OBJECT_B));
    assert_mismatch(&reference, &missing);

    let mut extra = reference.clone();
    extra.insert(index(&extra, OBJECT_B), ("3D/Objects/extra.model", vec![9]));
    assert_mismatch(&reference, &extra);

    let mut renamed = reference.clone();
    let object_b = index(&renamed, OBJECT_B);
    renamed[object_b].0 = "3D/Objects/renamed.model";
    assert_mismatch(&reference, &renamed);
}

#[test]
fn sliced_archive_rejects_duplicate_parallel_member_names() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("duplicate.3mf");
    let mut entries = archive();
    let index_b = index(&entries, OBJECT_B);
    let alias = "3D/Objects/c_2.model";
    entries.insert(index_b, (alias, entries[index_b].1.clone()));
    write_zip(&path, &entries);
    let mut bytes = fs::read(&path).unwrap();
    let offsets = bytes
        .windows(alias.len())
        .enumerate()
        .filter_map(|(offset, name)| (name == alias.as_bytes()).then_some(offset))
        .collect::<Vec<_>>();
    assert_eq!(offsets.len(), 2);
    for offset in offsets {
        bytes[offset..offset + alias.len()].copy_from_slice(OBJECT_B.as_bytes());
    }
    fs::write(&path, bytes).unwrap();
    assert!(catch_unwind(|| read_members(&path)).is_err());
}

#[test]
fn sliced_archive_rejects_changed_parallel_member_payloads() {
    let reference = archive();
    let mut actual = reference.clone();
    let object_b = index(&actual, OBJECT_B);
    actual[object_b].1[0] ^= 1;
    assert_mismatch(&reference, &actual);

    let mut actual = reference.clone();
    let plate_b = index(&actual, GCODE_B);
    let checksum_b = index(&actual, CHECKSUM_B);
    actual[plate_b].1.extend_from_slice(b"G1 X21\n");
    actual[checksum_b].1 = digest(&actual[plate_b].1);
    assert_mismatch(&reference, &actual);
}

#[test]
fn sliced_archive_rejects_moved_checksums_and_parallel_spans() {
    let reference = archive();
    let mut actual = reference.clone();
    swap(&mut actual, CHECKSUM_A, CHECKSUM_B);
    assert_mismatch(&reference, &actual);

    let mut actual = reference.clone();
    let checksum_b = actual.remove(index(&actual, CHECKSUM_B));
    actual.push(checksum_b);
    assert_mismatch(&reference, &actual);
}

#[test]
fn sliced_archive_rejects_split_parallel_spans_even_when_archives_are_identical() {
    let mut split_gcode = archive();
    swap(&mut split_gcode, CHECKSUM_B, GCODE_A);
    assert_mismatch(&archive(), &split_gcode);
    assert_mismatch(&split_gcode, &split_gcode);

    let mut split_objects = archive();
    swap(&mut split_objects, OBJECT_B, CHECKSUM_A);
    assert_mismatch(&archive(), &split_objects);
    assert_mismatch(&split_objects, &split_objects);
}

fn archive() -> Entries {
    let plate_a = [BANNER, b"G1 X10\n"].concat();
    let plate_b = [BANNER, b"G1 X20\n"].concat();
    vec![
        ("3D/3dmodel.model", vec![0]),
        (OBJECT_A, vec![1]),
        (OBJECT_B, vec![2]),
        (CHECKSUM_A, digest(&plate_a)),
        (CHECKSUM_B, digest(&plate_b)),
        (GCODE_A, plate_a),
        (GCODE_B, plate_b),
    ]
}

fn digest(payload: &[u8]) -> Vec<u8> {
    format!("{:X}", Md5::digest(payload)).into_bytes()
}

fn index(entries: &Entries, name: &str) -> usize {
    entries.iter().position(|entry| entry.0 == name).unwrap()
}

fn swap(entries: &mut Entries, left: &str, right: &str) {
    let (left, right) = (index(entries, left), index(entries, right));
    entries.swap(left, right);
}

fn write_zip(path: &Path, entries: &Entries) {
    let mut zip = ZipWriter::new(File::create(path).unwrap());
    for (name, payload) in entries {
        zip.start_file(*name, SimpleFileOptions::default()).unwrap();
        zip.write_all(payload).unwrap();
    }
    zip.finish().unwrap();
}

fn compare_archives(reference: &Entries, actual: &Entries) {
    let (reference, actual) = read_archives(reference, actual);
    compare_members(reference, actual);
}

fn assert_mismatch(reference: &Entries, actual: &Entries) {
    let (reference, actual) = read_archives(reference, actual);
    assert!(catch_unwind(AssertUnwindSafe(|| compare_members(reference, actual))).is_err());
}

fn read_archives(reference: &Entries, actual: &Entries) -> (Vec<Member>, Vec<Member>) {
    let dir = tempfile::tempdir().unwrap();
    let a = dir.path().join("reference.3mf");
    let b = dir.path().join("actual.3mf");
    write_zip(&a, reference);
    write_zip(&b, actual);
    (read_members(&a), read_members(&b))
}
