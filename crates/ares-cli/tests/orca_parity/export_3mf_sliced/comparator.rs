use std::fs;
use std::io::{Cursor, Read};
use std::path::Path;

use md5::{Digest, Md5};
use regex::bytes::Regex;
use zip::{CompressionMethod, ZipArchive};

pub(super) struct Member {
    pub(super) name: String,
    compression: CompressionMethod,
    central_header: [u8; 8],
    local_header: [u8; 6],
    attributes: [u8; 8],
    extra: Vec<u8>,
    comment: String,
    pub(super) bytes: Vec<u8>,
}

pub(super) fn read_members(path: &Path) -> Vec<Member> {
    let archive = fs::read(path).unwrap();
    let mut zip = ZipArchive::new(Cursor::new(&archive)).unwrap();
    // ZipArchive indexes by name and would silently collapse duplicates.
    let mut next_central = zip.central_directory_start() as usize;
    let members = (0..zip.len())
        .map(|index| {
            let mut entry = zip.by_index(index).unwrap();
            let mut bytes = Vec::new();
            entry.read_to_end(&mut bytes).unwrap();
            let central = entry.central_header_start() as usize;
            assert_eq!(central, next_central, "ZIP member omitted or out of order");
            next_central = central
                + 46
                + [28, 30, 32]
                    .into_iter()
                    .map(|offset| {
                        usize::from(u16::from_le_bytes(
                            archive[central + offset..central + offset + 2]
                                .try_into()
                                .unwrap(),
                        ))
                    })
                    .sum::<usize>();
            let local = entry.header_start() as usize;
            Member {
                name: entry.name().to_owned(),
                compression: entry.compression(),
                central_header: archive[central + 4..central + 12].try_into().unwrap(),
                local_header: archive[local + 4..local + 10].try_into().unwrap(),
                attributes: archive[central + 34..central + 42].try_into().unwrap(),
                extra: entry.extra_data().unwrap_or_default().to_vec(),
                comment: entry.comment().to_owned(),
                bytes,
            }
        })
        .collect();
    assert!(
        !archive[next_central..].starts_with(b"PK\x01\x02"),
        "ZIP member omitted at the end of the central directory"
    );
    members
}

fn is_object_model(name: &str) -> bool {
    name.strip_prefix("3D/Objects/")
        .and_then(|file| file.strip_suffix(".model"))
        .is_some_and(|stem| !stem.is_empty() && !stem.contains('/'))
}

fn is_plate_gcode(name: &str) -> bool {
    name.strip_prefix("Metadata/plate_")
        .and_then(|file| file.strip_suffix(".gcode"))
        .is_some_and(|plate| {
            !plate.is_empty()
                && !plate.starts_with('0')
                && plate.bytes().all(|byte| byte.is_ascii_digit())
        })
}

fn sort_parallel_span(members: &mut [Member], belongs: fn(&str) -> bool) {
    let Some(start) = members.iter().position(|member| belongs(&member.name)) else {
        return;
    };
    let len = members[start..]
        .iter()
        .take_while(|member| belongs(&member.name))
        .count();
    let (span, rest) = members[start..].split_at_mut(len);
    assert!(
        rest.iter().all(|member| !belongs(&member.name)),
        "split ZIP member span at {}",
        span[0].name
    );
    span.sort_unstable_by(|a, b| a.name.cmp(&b.name));
}

fn normalize_plate_gcodes(members: &mut [Member], banner: &Regex) {
    for index in 0..members.len() {
        if !is_plate_gcode(&members[index].name) {
            continue;
        }
        let checksum = format!("{}.md5", members[index].name);
        let checksum_index = members
            .iter()
            .position(|member| member.name == checksum)
            .unwrap();
        let gcode = &members[index].bytes;
        assert_eq!(
            members[checksum_index].bytes,
            format!("{:X}", Md5::digest(gcode)).as_bytes(),
            "{checksum}"
        );
        assert_eq!(
            banner.find_iter(gcode).count(),
            1,
            "{}",
            members[index].name
        );
        let normalized = banner
            .replace(
                gcode,
                b"; generated by <producer> on <timestamp>".as_slice(),
            )
            .into_owned();
        members[checksum_index].bytes = format!("{:X}", Md5::digest(&normalized)).into_bytes();
        members[index].bytes = normalized;
    }
}

pub(super) fn compare_members(mut native: Vec<Member>, mut ares: Vec<Member>) {
    let banner = Regex::new(
        r"(?m)^; generated by [^\r\n]+ on [0-9]{4}-[0-9]{2}-[0-9]{2} at [0-9]{2}:[0-9]{2}:[0-9]{2}$",
    )
    .unwrap();
    for members in [&mut native, &mut ares] {
        sort_parallel_span(members, is_object_model);
        sort_parallel_span(members, is_plate_gcode);
        normalize_plate_gcodes(members, &banner);
    }
    assert_eq!(native.len(), ares.len());
    for (mut native, mut ares) in native.into_iter().zip(ares) {
        assert_eq!(native.name, ares.name);
        assert_eq!(native.compression, ares.compression, "{}", native.name);
        assert_eq!(
            native.central_header, ares.central_header,
            "{} central version, flags and method",
            native.name
        );
        assert_eq!(
            native.local_header, ares.local_header,
            "{} local version, flags and method",
            native.name
        );
        assert_eq!(
            native.attributes, ares.attributes,
            "{} attributes",
            native.name
        );
        assert_eq!(native.extra, ares.extra, "{} extra fields", native.name);
        assert_eq!(native.comment, ares.comment, "{} comment", native.name);

        if native.name == "Metadata/model_settings.config" && native.bytes != ares.bytes {
            native.bytes = model_settings_in_object_id_order(&native.bytes);
            ares.bytes = model_settings_in_object_id_order(&ares.bytes);
        }
        let mismatch = native
            .bytes
            .iter()
            .zip(&ares.bytes)
            .position(|(n, a)| n != a);
        assert!(
            mismatch.is_none() && native.bytes.len() == ares.bytes.len(),
            "{} differs at byte {mismatch:?}: lengths Native {}, Ares {}",
            native.name,
            native.bytes.len(),
            ares.bytes.len(),
        );
    }
}

fn model_settings_in_object_id_order(bytes: &[u8]) -> Vec<u8> {
    // bbs_3mf.cpp:6218,8306: Native iterates object records by model pointer.
    // Reorder only the complete top-level records, without reserializing XML.
    let object = Regex::new(r#"(?ms)^  <object id="([0-9]+)"[^>\n]*>\n.*?^  </object>\n"#).unwrap();
    let mut records: Vec<_> = object
        .captures_iter(bytes)
        .map(|record| (record.get(1).unwrap().as_bytes(), record.get(0).unwrap()))
        .collect();
    if records.len() < 2 {
        return bytes.to_vec();
    }
    assert!(
        records
            .windows(2)
            .all(|pair| pair[0].1.end() == pair[1].1.start())
    );
    let start = records[0].1.start();
    let end = records.last().unwrap().1.end();
    records.sort_unstable_by_key(|record| record.0);
    assert!(records.windows(2).all(|pair| pair[0].0 != pair[1].0));
    let mut ordered = Vec::with_capacity(bytes.len());
    ordered.extend_from_slice(&bytes[..start]);
    for (_, record) in records {
        ordered.extend_from_slice(record.as_bytes());
    }
    ordered.extend_from_slice(&bytes[end..]);
    ordered
}
