//! Same-argv E2E for native `--load-settings`/`--load-filaments`
//! (spec: docs/superpowers/specs/2026-10-09-cli-load-settings-filaments.md).
//! RED: the ares argv does not exist yet — the CLI must accept the native
//! flags, slice the same model with the same preset files, and match the
//! runtime-Native reference whole-file (generator banner normalized).
#![cfg(target_os = "linux")]

use std::{fs, path::Path, process::Command};

use serde_json::{Map, Value};

fn preset_files(directory: &Path, vendor_name: &str, printer: &str) -> Vec<String> {
    let profiles_root = crate::runner::repo_root().join("OrcaSlicer/resources/profiles");
    let profiles = crate::presets::VendorProfiles::load(&profiles_root, vendor_name).unwrap();
    let selected = crate::select_printer(&profiles, vendor_name, printer).unwrap();
    let mut paths = Vec::new();
    let mut write = |kind: &str, filename: &str, mut fields: Map<String, Value>| {
        fields.insert("type".to_owned(), Value::String(kind.to_owned()));
        fields.insert("from".to_owned(), Value::String("system".to_owned()));
        fields.insert("instantiation".to_owned(), Value::String("true".to_owned()));
        let path = directory.join(filename);
        fs::write(
            &path,
            serde_json::to_vec_pretty(&Value::Object(fields)).unwrap(),
        )
        .unwrap();
        paths.push(path.to_str().unwrap().to_owned());
    };
    write(
        "machine",
        "machine.json",
        profiles.machine(printer).unwrap(),
    );
    write(
        "process",
        "process.json",
        profiles.process(&selected.process).unwrap(),
    );
    for (index, name) in selected.filaments.iter().enumerate() {
        write(
            "filament",
            &format!("filament-{index}.json"),
            profiles.filament(name).unwrap(),
        );
    }
    paths
}

fn banner_normalized(bytes: &[u8]) -> Vec<u8> {
    bytes
        .split(|byte| *byte == b'\n')
        .filter(|line| !line.starts_with(b"; generated by "))
        .fold(Vec::new(), |mut acc, line| {
            acc.extend_from_slice(line);
            acc.push(b'\n');
            acc
        })
}

#[tokio::test]
async fn orca_parity_load_settings_cli_ender3_whole_file() {
    let Some(runner) = crate::runner::OrcaRunner::from_env().unwrap() else {
        return;
    };
    let directory = tempfile::Builder::new()
        .prefix("load-settings-cli-ender3-")
        .tempdir()
        .unwrap()
        .keep();
    let presets = preset_files(&directory, "Creality", "Creality Ender-3 0.4 nozzle");
    let machine_process = format!("{};{}", presets[0], presets[1]);
    let filaments = presets[2..].join(";");
    fs::write(
        directory.join("cube10.stl"),
        // Identical pre-positioned STL for both slicers (bed-center shift;
        // `--arrange 0` keeps the model's own coordinates — the arrange
        // port is a deferred upstream slice, same convention as
        // runner/profile_entry.rs). Raw cube10 sits outside Ender-3's bed
        // and Native would reject it with CLI_NO_SUITABLE_OBJECTS (-50,
        // Utils.hpp:52).
        crate::runner::placed_cube(
            &fs::read(crate::runner::repo_root().join("tests/parity/cube10.stl")).unwrap(),
        ),
    )
    .unwrap();

    // Runtime Native with the documented CLI shape
    // (`PrintConfig.cpp:10890-10901`): `--load-settings "m;p"`
    // `--load-filaments "f0"`. `--arrange 0` pins both slicers to the
    // model's own coordinates (the arrange port is a deferred upstream
    // slice; same convention as runner/profile_entry.rs:165).
    stages_run(
        &runner,
        &directory,
        &[
            "--slice",
            "0",
            "--load-settings",
            &machine_process,
            "--load-filaments",
            &filaments,
            "--arrange",
            "0",
            "--outputdir",
            "native-output",
            "cube10.stl",
        ],
    );
    let native = fs::read(directory.join("native-output/plate_1.gcode")).unwrap();

    // Same argv against the ares CLI binary.
    let output = Command::new(env!("CARGO_BIN_EXE_ares"))
        .current_dir(&directory)
        .args([
            "slice",
            "--load-settings",
            &machine_process,
            "--load-filaments",
            &filaments,
            "-o",
            "ares.gcode",
            "cube10.stl",
        ])
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "ares rejected the native --load-settings/--load-filaments argv:\n{}",
        String::from_utf8_lossy(&output.stderr),
    );
    let ares = fs::read(directory.join("ares.gcode")).unwrap();

    assert_eq!(
        banner_normalized(&native),
        banner_normalized(&ares),
        "same-argv whole-file divergence; artifacts {}",
        directory.display(),
    );
}

fn stages_run(runner: &crate::runner::OrcaRunner, directory: &Path, args: &[&str]) {
    crate::runner::stages::run(
        runner.bin(),
        args.iter().map(|arg| arg.to_string()),
        crate::runner::stages::Stage::Slice,
        directory,
    )
    .unwrap();
}

fn load_settings_3mf_fixture(name: &str) -> std::path::PathBuf {
    crate::runner::repo_root()
        .join("tests/parity/validation/load-settings-3mf")
        .join(name)
}

fn parse_return_code(stdout: &[u8]) -> i32 {
    // "run found error, return -19, exit...\n"
    let text = std::str::from_utf8(stdout).unwrap();
    text.split("return ")
        .nth(1)
        .unwrap()
        .split(',')
        .next()
        .unwrap()
        .parse()
        .unwrap()
}

/// The `-19` rejection witness (`OrcaSlicer.cpp:1682-1690`): the embedded
/// `post_process: [""]` is a non-empty array, and the check lives in the
/// 3MF load block before `--load-settings` processing, so Native rejects
/// while the Ares guard (`main.rs`) exits 1.
#[test]
fn orca_parity_load_settings_3mf_post_process_reject() {
    let Some(runner) = crate::runner::OrcaRunner::from_env().unwrap() else {
        return;
    };
    let artifacts = tempfile::Builder::new()
        .prefix("load-settings-3mf-reject-")
        .tempdir()
        .unwrap()
        .keep();
    let project = load_settings_3mf_fixture("input.3mf");
    let settings = ["machine.json", "process.json"]
        .into_iter()
        .map(|name| {
            load_settings_3mf_fixture(name)
                .to_string_lossy()
                .into_owned()
        })
        .collect::<Vec<_>>();
    let filaments = [load_settings_3mf_fixture("filament-0.json")
        .to_string_lossy()
        .into_owned()];
    let rejection = crate::runner::EarlyExit::Postprocess;
    let native = runner
        .load_settings_early_reference(&project, &settings, &filaments, rejection)
        .unwrap();
    let hit = runner
        .load_settings_early_reference(&project, &settings, &filaments, rejection)
        .unwrap();
    assert_eq!(native.directory, hit.directory);
    assert_eq!(native.stdout, hit.stdout);
    assert_eq!(native.stderr, hit.stderr);
    assert_eq!(native.result_json, hit.result_json);
    assert_eq!(native.gcode, hit.gcode);
    assert!(native.gcode.is_none());
    fs::write(artifacts.join("native.stdout"), &native.stdout).unwrap();
    fs::write(artifacts.join("native.stderr"), &native.stderr).unwrap();
    fs::write(artifacts.join("native.result.json"), &native.result_json).unwrap();
    fs::copy(
        native.directory.join("receipt.json"),
        artifacts.join("native.receipt.json"),
    )
    .unwrap();

    let gcode = artifacts.join("gcode");
    let output = Command::new(env!("CARGO_BIN_EXE_ares"))
        .current_dir(&artifacts)
        .args([
            "slice",
            "--load-settings",
            &settings.join(";"),
            "--load-filaments",
            &filaments.join(";"),
            "-o",
        ])
        .arg(&gcode)
        .arg(&project)
        .output()
        .unwrap();
    fs::write(artifacts.join("stdout"), &output.stdout).unwrap();
    fs::write(artifacts.join("stderr"), &output.stderr).unwrap();
    fs::write(
        artifacts.join("exit"),
        format!("{:?}\n", output.status.code()),
    )
    .unwrap();
    let code = parse_return_code(&native.stdout);
    assert_eq!(code, -19, "native return code: {artifacts:?}");
    // flush_and_exit returns the negative code; POSIX exposes 256+n.
    assert_eq!(
        output.status.code(),
        Some(256 - 19),
        "ares channels: {artifacts:?}"
    );
    assert_eq!(output.stdout, native.stdout, "stdout channel");
    assert_eq!(output.stderr, native.stderr, "stderr channel");
    assert_eq!(
        crate::native_wall_clock::result_comparison_bytes(
            &fs::read(artifacts.join("result.json")).unwrap(),
        ),
        crate::native_wall_clock::result_comparison_bytes(&native.result_json),
        "complete result.json bytes: {artifacts:?}"
    );
    assert!(!gcode.exists(), "early rejection must not export G-code");
}

/// The compatible forward case: the witness 3MF with the embedded
/// `post_process` emptied; the loaded process's `compatible_printers`
/// names the loaded machine (`OrcaSlicer.cpp:2576-2585` branch 1), so
/// Native slices and the whole-file output must match (guard-normalized).
#[test]
fn orca_parity_load_settings_3mf_compatible_whole_file() {
    let Some(runner) = crate::runner::OrcaRunner::from_env().unwrap() else {
        return;
    };
    let directory = tempfile::Builder::new()
        .prefix("load-settings-3mf-compatible-")
        .tempdir()
        .unwrap()
        .keep();
    let project = load_settings_3mf_fixture("compatible-input.3mf");
    let machine_process = [
        load_settings_3mf_fixture("machine.json"),
        load_settings_3mf_fixture("process.json"),
    ]
    .iter()
    .map(|path| path.to_string_lossy().into_owned())
    .collect::<Vec<_>>()
    .join(";");
    let filaments = load_settings_3mf_fixture("compatible-filament-0.json")
        .to_string_lossy()
        .into_owned();
    stages_run(
        &runner,
        &directory,
        &[
            "--slice",
            "0",
            "--load-settings",
            &machine_process,
            "--load-filaments",
            &filaments,
            // Native's default `need_arrange` re-places the model at the
            // loaded bed center; `--arrange 0` pins the embedded transform
            // (the arrange port is a deferred upstream slice — same
            // convention as the STL case and `runner/profile_entry.rs`).
            "--arrange",
            "0",
            "--outputdir",
            "native-output",
            project.to_str().unwrap(),
        ],
    );
    let native = fs::read(directory.join("native-output/plate_1.gcode")).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_ares"))
        .current_dir(&directory)
        .args([
            "slice",
            "--load-settings",
            &machine_process,
            "--load-filaments",
            &filaments,
            "-o",
            "ares.gcode",
        ])
        .arg(&project)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "ares rejected the 3MF --load-settings argv:\n{}",
        String::from_utf8_lossy(&output.stderr),
    );
    let ares = fs::read(directory.join("ares.gcode")).unwrap();
    assert_eq!(
        banner_normalized(&native),
        banner_normalized(&ares),
        "3MF+load-settings whole-file divergence; artifacts {}",
        directory.display(),
    );
}
