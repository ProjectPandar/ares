//! Whole-file byte-compare on the stock machine-matrix snapmaker-artisan
//! detour residual (`stock/Snapmaker/Snapmaker Artisan (0.4 nozzle)` +
//! the common fixture `tests/parity/hole-to-polyhole/block-hole.3mf`,
//! stock defaults — the process preset bakes `reduce_crossing_wall=1`).
//!
//! RED for the avoid-crossing internal-boundary top-surface inset
//! (`AvoidCrossingPerimeters.cpp:1123-1125`): upstream carves the unioned
//! top fill surfaces with `offset_ex(top_layer_polygons,
//! -1.2 * perimeter_offset)`, whose `offset_ex` defaults are jtMiter /
//! `DefaultMiterLimit = 3.` (`ClipperUtils.hpp:19,27`). Ares's
//! `boundary.rs build_with_spacing` inset used `JoinType::Round` with
//! miter limit 2.0, emitting arc vertex chains (≈650-vertex internal
//! boundary contours) where the oracle keeps miter corners (a 53-vertex
//! contour); `simplify_travel` then stops on a different vertex lattice
//! and three interior travel vertices of the Z8.44 hop detour differ
//! (e.g. `G1 X195.476 Y204.524` oracle vs `G1 X195.494 Y204.538`).
//!
//! The only normalized line is `; generated by`.

use super::*;

fn normalized(bytes: &[u8]) -> Vec<String> {
    std::str::from_utf8(bytes)
        .unwrap()
        .lines()
        .map(|line| {
            if line.starts_with("; generated by") {
                "; generated by"
            } else {
                line
            }
        })
        .map(str::to_owned)
        .collect()
}

#[test]
fn orca_parity_snapmaker_artisan_detour() {
    let Some(runner) = OrcaRunner::from_env().unwrap_or_else(|error| panic!("{error}")) else {
        return;
    };
    let profiles = VendorProfiles::load(&profiles_root(), "Snapmaker").unwrap();
    let selection =
        parity::select_printer(&profiles, "Snapmaker", "Snapmaker Artisan (0.4 nozzle)").unwrap();
    let machine = profiles.machine(&selection.printer).unwrap();
    let process = profiles.process(&selection.process).unwrap();
    let filaments = selection
        .filaments
        .iter()
        .map(|name| profiles.filament(name))
        .collect::<Result<Vec<_>, _>>()
        .unwrap();
    let exported = runner
        .export_case(
            &CaseInputs {
                label: "snapmaker-artisan-detour",
                machine: &machine,
                process: &process,
                filaments: &filaments,
            },
            &serde_json::Map::new(),
            &runner::repo_root().join("tests/parity/hole-to-polyhole/block-hole.3mf"),
        )
        .unwrap();
    let sliced = runner.slice_case(&exported).unwrap();
    // Attribution gate: the seeded oracle must reproduce its own output
    // before the byte-compare is meaningful.
    let rerun = runner.rerun_reference(&exported).unwrap();
    assert_eq!(
        normalized(&sliced.reference),
        normalized(&rerun.reference),
        "seeded oracle is not self-stable on this fixture"
    );

    let actual_bytes = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap()
        .block_on(ares_core::slice_project(
            &sliced.project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();
    assert_eq!(
        normalized(&actual_bytes),
        normalized(&sliced.reference),
        "Snapmaker Artisan detour diverged",
    );
}
