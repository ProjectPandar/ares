//! Custom G-code formatting function `zdigits`
//! (`PlaceholderParser.cpp:2324-2325` grammar entry, `expr::digits<true>`
//! `:663-687`).
//!
//! `zdigits` is the zero-padded twin of `digits`: the shared
//! `expr::digits<leading_zeros>` formats with C `sprintf("%0*.*lf")` for the
//! decimals form and `sprintf("%0*d")` over `as_i_rounded()` for the plain
//! form, so `zdigits(5.5, 3)` renders `006`.
//!
//! Two stock fixtures whose `machine_start_gcode` keeps the stock template
//! and appends the marker `;W4PH_MS_ZDIGITS={zdigits(5.5, 3)}` (line 83 on
//! MK4 `cube_with_hole`, line 9 on the K1 variant).
//! RED: Ares's function table had no `zdigits` arm, so slicing aborted with
//! `unknown function: zdigits in zdigits(5.5, 3)` (exit 156) while Native
//! renders `006` and exports.
//!
//! Witness standard: the Native reference is captured twice and byte-stable
//! (`slice_case` + `rerun_reference`), the marker renders `006` in the
//! reference, and Ares's complete output matches the reference byte-for-byte
//! except the single `; generated by` line.

use super::*;

fn normalized(bytes: &[u8]) -> Vec<String> {
    std::str::from_utf8(bytes)
        .unwrap()
        .lines()
        .map(|line| {
            if line.starts_with("; generated by") {
                "; generated by"
            } else {
                line
            }
        })
        .map(str::to_owned)
        .collect()
}

fn assert_zdigits_matches_native(case: &str) {
    let Some(runner) = OrcaRunner::from_env().unwrap_or_else(|error| panic!("{error}")) else {
        return;
    };
    let fixture = runner::repo_root().join(format!(
        "tests/parity/validation/cli-exit/custom-gcode/{case}.3mf"
    ));
    let project = std::fs::read(&fixture).unwrap();
    let exported = runner.fixture_case(case, project).unwrap();
    let sliced = runner.slice_case(&exported).unwrap();
    let rerun = runner.rerun_reference(&exported).unwrap();
    assert_eq!(
        normalized(&sliced.reference),
        normalized(&rerun.reference),
        "seeded oracle is not self-stable on {case}"
    );
    let marker = b";W4PH_MS_ZDIGITS=006";
    assert!(
        sliced
            .reference
            .windows(marker.len())
            .any(|window| window == marker),
        "Native must render zdigits(5.5, 3) as 006 on {case}"
    );

    let actual_bytes = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap()
        .block_on(crate::runner::application::slice_project(
            &sliced.project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();
    assert_eq!(
        normalized(&actual_bytes),
        normalized(&sliced.reference),
        "{case}: zdigits output diverged",
    );
}

#[test]
fn custom_gcode_zdigits_mk4_matches_native() {
    assert_zdigits_matches_native("mk4-ms-zdigits");
}

#[test]
fn custom_gcode_zdigits_k1_matches_native() {
    assert_zdigits_matches_native("k1-ms-zdigits");
}
