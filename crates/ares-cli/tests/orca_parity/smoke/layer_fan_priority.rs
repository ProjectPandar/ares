//! Layer-time fan branch priority on the K1 (Klipper) preset with
//! `fan_cooling_layer_time` < `slow_down_layer_time`.
//!
//! RED for `CoolingBuffer.cpp:760-767` (`change_extruder_set_fan`): the
//! full-throttle branch `layer_time < slow_down_layer_time →
//! fan_speed_new = fan_max_speed` is tested FIRST, and the interpolation
//! `else if (layer_time < fan_cooling_layer_time)` uses
//! `t = (layer_time - slow_down)/(fan_cooling - slow_down)` (double) with
//! `int(floor(t*fan_min_speed + (1.-t)*fan_max_speed) + 0.5)` — the +0.5
//! outside `floor` truncates back, i.e. plain floor. When
//! `fan_cooling_layer_time < slow_down_layer_time` the else-if is
//! unreachable and every layer below `slow_down_layer_time` goes full
//! throttle.
//!
//! Ares `part_cooling_fan.rs base_speed_for_runtime_layer_time` tested
//! `layer_time >= fan_cooling_layer_time → baseline` first, so layers with
//! an estimated time in `[fan_cooling, slow_down)` kept the
//! `fan_min_speed` baseline instead of `fan_max_speed`.
//!
//! Case: Creality K1 (stock `slow_down_layer_time=8`, `fan_max_speed=100`)
//! with `fan_min_speed=20` + `fan_cooling_layer_time=5` patched into the
//! filament preset, fixture `step-tower.obj` (24x24x2 base + 12x12x6 mid +
//! 6x6x10 top — the mid-section layers land in [5,8)s). Seeded oracle with
//! rerun self-stability gate; `; generated by` normalization only.

use super::*;

fn normalized(bytes: &[u8]) -> Vec<String> {
    std::str::from_utf8(bytes)
        .unwrap()
        .lines()
        .map(|line| {
            if line.starts_with("; generated by") {
                "; generated by"
            } else {
                line
            }
        })
        .map(str::to_owned)
        .collect()
}

#[test]
fn layer_fan_priority() {
    let Some(runner) = OrcaRunner::from_env().unwrap_or_else(|error| panic!("{error}")) else {
        return;
    };
    let profiles = VendorProfiles::load(&profiles_root(), "Creality").unwrap();
    let selection =
        parity::select_printer(&profiles, "Creality", "Creality K1 (0.4 nozzle)").unwrap();
    let machine = profiles.machine(&selection.printer).unwrap();
    let process = profiles.process(&selection.process).unwrap();
    let mut filaments = selection
        .filaments
        .iter()
        .map(|name| profiles.filament(name))
        .collect::<Result<Vec<_>, _>>()
        .unwrap();
    for filament in &mut filaments {
        filament.insert("fan_min_speed".to_owned(), serde_json::json!(["20"]));
        filament.insert(
            "fan_cooling_layer_time".to_owned(),
            serde_json::json!(["5"]),
        );
    }
    let exported = runner
        .export_case(
            &CaseInputs {
                label: "layer-fan-priority",
                machine: &machine,
                process: &process,
                filaments: &filaments,
            },
            &serde_json::Map::new(),
            &runner::repo_root().join("tests/parity/layer-fan-priority/step-tower.obj"),
        )
        .unwrap();
    let sliced = runner.slice_case(&exported).unwrap();
    // Attribution gate: the seeded oracle must reproduce its own output
    // before the byte-compare is meaningful.
    let rerun = runner.rerun_reference(&exported).unwrap();
    assert_eq!(
        normalized(&sliced.reference),
        normalized(&rerun.reference),
        "seeded oracle is not self-stable on this fixture"
    );

    let actual_bytes = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap()
        .block_on(ares_core::slice_project(
            &sliced.project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();
    assert_eq!(
        normalized(&actual_bytes),
        normalized(&sliced.reference),
        "layer fan branch priority diverged",
    );
}
