pub(super) fn compare_slice(selection: &str, count: usize, arrange: Option<&str>, missing: bool) {
    let Some(runner) = OrcaRunner::from_env().unwrap() else {
        return;
    };
    let root = tempfile::Builder::new()
        .prefix("direct-stl-slice-")
        .tempdir_in(artifacts::root_from_env().unwrap())
        .unwrap()
        .keep();
    let presets = preset_files(&root, "Creality", "Creality Ender-3 0.4 nozzle");
    let settings = presets[..2].join(";");
    let filaments = presets[2..].join(";");
    let inputs = (0..count)
        .map(|i| {
            let input = root.join(format!("block-{i}.stl"));
            if !missing {
                fs::write(&input, block_stl(108.0 + 24.0 * i as f32)).unwrap();
            }
            input
        })
        .collect::<Vec<_>>();
    let run = |bin: &Path, name: &str| {
        let cwd = root.join(name);
        let dir = cwd.join("out");
        fs::create_dir_all(&dir).unwrap();
        let temp = cwd.join("tmp");
        fs::create_dir(&temp).unwrap();
        let mut command = Command::new(bin);
        command
            .env("TMPDIR", temp)
            .current_dir(&cwd)
            .args(["--slice", selection, "--outputdir", "out"])
            .args(["--load-settings", &settings, "--load-filaments", &filaments]);
        if let Some(arrange) = arrange {
            command.args(["--arrange", arrange]);
        }
        let output = command.args(&inputs).output().unwrap();
        fs::write(cwd.join("exit"), format!("{:?}\n", output.status.code())).unwrap();
        fs::write(cwd.join("stderr"), &output.stderr).unwrap();
        (dir, output)
    };
    let (native_dir, native) = run(runner.bin(), "native");
    let expected_files = if missing {
        &["result.json"][..]
    } else {
        &["plate_1.gcode", "result.json"][..]
    };
    assert_eq!(
        native.status.code(),
        Some(if missing { 253 } else { 0 }),
        "{root:?}"
    );
    assert_eq!(inventory(&native_dir), expected_files, "{root:?}");
    let (ares_dir, ares) = run(Path::new(env!("CARGO_BIN_EXE_ares")), "ares");
    assert_eq!(ares.status.code(), native.status.code(), "{root:?}");
    assert!(ares.stderr == native.stderr, "stderr differs at {root:?}");
    assert_eq!(inventory(&ares_dir), expected_files, "{root:?}");
    assert_eq!(
        normalized_report(&ares_dir),
        normalized_report(&native_dir),
        "{root:?}"
    );
    if !missing {
        assert!(
            normalized_gcode(&ares_dir.join("plate_1.gcode"))
                == normalized_gcode(&native_dir.join("plate_1.gcode")),
            "G-code differs at {root:?}"
        );
    }
}

pub(super) fn inventory(dir: &Path) -> Vec<String> {
    let mut files = fs::read_dir(dir)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .collect::<Vec<_>>();
    files.sort_unstable();
    files
}

pub(super) fn normalized_gcode(path: &Path) -> Vec<u8> {
    fs::read(path)
        .unwrap()
        .split_inclusive(|byte| *byte == b'\n')
        .filter(|line| !line.starts_with(b"; generated by "))
        .flatten()
        .copied()
        .collect()
}

pub(super) fn normalized_report(dir: &Path) -> Value {
    let mut result: Value =
        serde_json::from_slice(&fs::read(dir.join("result.json")).unwrap()).unwrap();
    let zero_timing = |object: &mut Value, key: &str| {
        assert!(object[key].is_u64(), "{key} at {dir:?}");
        object[key] = Value::from(0);
    };
    zero_timing(&mut result, "prepare_time");
    zero_timing(&mut result, "export_time");
    if let Some(plates) = result.get_mut("sliced_plates") {
        for plate in plates.as_array_mut().unwrap() {
            zero_timing(plate, "sliced_time");
            zero_timing(plate, "sliced_time_with_cache");
        }
    }
    result
}

pub(super) fn block_stl(x: f32) -> Vec<u8> {
    square_stl([x, 122.0], 10.0, 10.0)
}

pub(super) fn square_stl([x, y]: [f32; 2], edge: f32, height: f32) -> Vec<u8> {
    let vertices = [
        [x, y, 0.0],
        [x + edge, y, 0.0],
        [x + edge, y + edge, 0.0],
        [x, y + edge, 0.0],
        [x, y, height],
        [x + edge, y, height],
        [x + edge, y + edge, height],
        [x, y + edge, height],
    ];
    let faces = [
        [0, 2, 1],
        [0, 3, 2],
        [4, 5, 6],
        [4, 6, 7],
        [0, 1, 5],
        [0, 5, 4],
        [1, 2, 6],
        [1, 6, 5],
        [2, 3, 7],
        [2, 7, 6],
        [3, 0, 4],
        [3, 4, 7],
    ];
    let mut bytes = vec![0; 80];
    bytes.extend(12_u32.to_le_bytes());
    for face in faces {
        bytes.extend([0; 12]);
        for index in face {
            for coordinate in vertices[index] {
                bytes.extend(coordinate.to_le_bytes());
            }
        }
        bytes.extend([0; 2]);
    }
    bytes
}
