//! Whole-file byte-compare on the stock matrix C1 residual
//! (`stock/Creality/Creality Sermoon V1 0.4 nozzle` + `cube10.stl`,
//! `slowdown_for_curled_perimeters=1`, `role_based_wipe_speed=1`).
//!
//! RED for `docs/superpowers/specs/2026-10-07-emit-speed-curl-residual.md`:
//! upstream's sloped wall paths run through the processed `extrude_path`
//! loop (`GCode.cpp:7028-7115`) so `m_current_speed` ends at the last
//! emitted segment speed and `Wipe::wipe` (`GCode.cpp:340`,
//! `role_based_wipe_speed=1`) picks that speed. Ares routes slope paths
//! through `scarf::emit_segments`, which never updates
//! `extrusion_feedrate`, leaving it at `points[0].speed * 60` — the wipe
//! emits `G1 F4800`/`F6120` where the oracle emits `F5580`/`F6818.82`.
//!
//! The only normalized line is `; generated by`; progress lines and all
//! F/E/X/Y/Z words must match byte-for-byte.

use crate::{CaseInputs, OrcaRunner, VendorProfiles, runner};

fn normalized(bytes: &[u8]) -> Vec<String> {
    std::str::from_utf8(bytes)
        .unwrap()
        .lines()
        .map(|line| {
            if line.starts_with("; generated by") {
                "; generated by"
            } else {
                line
            }
        })
        .map(str::to_owned)
        .collect()
}

#[test]
fn sermoon_v1_whole_file() {
    let Some(runner) = OrcaRunner::from_env().unwrap_or_else(|error| panic!("{error}")) else {
        return;
    };
    let profiles = VendorProfiles::load(
        &runner::repo_root().join("OrcaSlicer/resources/profiles"),
        "Creality",
    )
    .unwrap();
    let selection =
        crate::select_printer(&profiles, "Creality", "Creality Sermoon V1 0.4 nozzle").unwrap();
    let machine = profiles.machine(&selection.printer).unwrap();
    let process = profiles.process(&selection.process).unwrap();
    let filaments = selection
        .filaments
        .iter()
        .map(|name| profiles.filament(name))
        .collect::<Result<Vec<_>, _>>()
        .unwrap();
    let exported = runner
        .export_case(
            &CaseInputs {
                label: "sermoon-v1-whole-file",
                machine: &machine,
                process: &process,
                filaments: &filaments,
            },
            &serde_json::Map::new(),
            &runner::repo_root().join("tests/parity/cube10.stl"),
        )
        .unwrap();
    runner::application::verify_value(
        &exported.project,
        "role_based_wipe_speed",
        &serde_json::json!("1"),
    )
    .unwrap();

    let sliced = runner.slice_case(&exported).unwrap();
    // Attribution gate: the seeded oracle must reproduce its own output
    // including progress placement before the byte-compare is meaningful.
    let rerun = runner.rerun_reference(&exported).unwrap();
    assert_eq!(
        normalized(&sliced.reference),
        normalized(&rerun.reference),
        "seeded oracle is not self-stable on this fixture"
    );

    let actual_bytes = tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap()
        .block_on(ares_core::slice_project(
            &sliced.project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap();
    assert_eq!(
        normalized(&actual_bytes),
        normalized(&sliced.reference),
        "Sermoon V1 whole-file diverged",
    );
}
