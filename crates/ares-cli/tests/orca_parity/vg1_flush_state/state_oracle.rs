//! Public processed-slice failure inventory: VG1 must update E/F without
//! appending a vertex; subsequent absolute E must use its endpoint, and the
//! queued virtual blocks assign time to the upstream dummy move (id zero).
use std::process::Command;

pub(super) fn processed(project: &[u8]) -> ares_core::ProcessedGCode {
    tokio::runtime::Builder::new_current_thread()
        .build()
        .unwrap()
        .block_on(crate::runner::application::slice_project_plate_processed(
            project,
            ares_core::GenerationMetadata::deterministic(2026, 8, 27, 0, 0, 0),
            None,
            &ares_core::ConfigOverrides::default(),
            ares_core::SlicerContext::new(0),
        ))
        .unwrap()
}

pub(super) fn check(project: &[u8]) {
    let processed = processed(project);
    let text = std::str::from_utf8(&processed.gcode).unwrap();
    let renamed = text.replacen(
        concat!(
            "; generated by Ares ",
            env!("CARGO_PKG_VERSION"),
            " on 1980-01-01 at 00:00:00"
        ),
        "; generated by OrcaSlicer 2.5.0",
        1,
    );
    assert_ne!(text, renamed);
    let directory = tempfile::Builder::new()
        .prefix("vg1_flush_state-state-oracle-")
        .tempdir()
        .unwrap()
        .keep();
    let input = directory.join("input.gcode");
    let csv = directory.join("native.csv");
    std::fs::write(&input, renamed).unwrap();
    let run = Command::new(std::env::var_os("ARES_PROCGCODE_BIN").unwrap())
        .arg("--process-gcode")
        .arg(&input)
        .arg("--dump-moves")
        .arg(&csv)
        .output()
        .unwrap();
    std::fs::write(
        directory.join("native.log"),
        [&run.stdout[..], &run.stderr[..]].concat(),
    )
    .unwrap();
    assert!(run.status.success(), "{:?}; {directory:?}", run.status);
    std::fs::write(
        directory.join("ares-moves.txt"),
        format!("{:#?}", processed.result.moves),
    )
    .unwrap();
    let source = text
        .lines()
        .position(|line| line == "G1 X25 Y10 E45")
        .unwrap()
        + 1;
    let native = std::fs::read_to_string(csv).unwrap();
    let rows = native
        .lines()
        .skip(1)
        .map(|row| row.split(',').collect::<Vec<_>>())
        .collect::<Vec<_>>();
    let expected = rows
        .iter()
        .find(|row| row[0].parse::<usize>().unwrap() == source && row[18] == "0")
        .unwrap();
    let actual = processed
        .result
        .moves
        .iter()
        .find(|vertex| vertex.gcode_id as usize == source && !vertex.internal_only)
        .unwrap();
    for (name, actual, column) in [
        ("delta_extruder", actual.delta_extruder, 8),
        ("feedrate", actual.feedrate, 9),
        ("x", actual.position[0], 5),
        ("y", actual.position[1], 6),
    ] {
        assert_eq!(
            actual.to_bits(),
            expected[column].parse::<f32>().unwrap().to_bits(),
            "{name}; {directory:?}"
        );
    }
    let dummy_time = rows[0][16].parse::<f32>().unwrap();
    assert!(dummy_time > 0.0);
    assert_eq!(
        processed.result.moves[0].time.to_bits(),
        dummy_time.to_bits(),
        "dummy time; {directory:?}"
    );
    let virtual_sources = text
        .lines()
        .enumerate()
        .filter(|(_, line)| line.starts_with(";VG1"))
        .map(|(index, _)| index as u32 + 1)
        .collect::<Vec<_>>();
    assert!(
        processed
            .result
            .moves
            .iter()
            .all(|vertex| !virtual_sources.contains(&vertex.gcode_id))
    );
}
