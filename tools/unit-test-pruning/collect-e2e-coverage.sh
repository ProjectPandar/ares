#!/usr/bin/env bash
# E2E-only coverage for unit-test pruning evidence. Runs orca_parity (seeded,
# which exercises every ares path the official suite does) + stock_project_whole_file.
set -euo pipefail
P=/nix/store/wahgmwqll1vg1svk64fjqgzfzq0q2asf-llvm-23.1.0-rc1
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"
if [ -n "${ARES_PARITY_ENV:-}" ]; then
  set -a
  source "$ARES_PARITY_ENV"
  set +a
fi
: "${ORCA_REPLAY_BIN:?select the v2.5.0-beta seed-only executable}"
: "${ARES_PARITY_ARTIFACT_ROOT:?select an external artifact directory}"
: "${ARES_ORCA_CACHE_DIR:?select an external reference cache}"
exec env \
  LLVM_COV=$P/bin/llvm-cov LLVM_PROFDATA=$P/bin/llvm-profdata \
  CARGO_INCREMENTAL=0 \
  ARES_ORCA_BIN="$ROOT/scripts/orca-seeded-parity.sh" \
  ORCA_REPLAY_SEED=0 ARES_PARITY_SEEDED_REFERENCE=1 \
  ARES_PARITY_BOOKKEEPING_REFERENCE=1 ARES_PARITY_BRIDGE_DIRECTION_REFERENCE=1 \
  ARES_PARITY_CLIPPED_LOOP_REFERENCE=1 ARES_PARITY_EMISSION_PHASES_REFERENCE=1 \
  ARES_PARITY_FILAMENT_STATS_REFERENCE=1 ARES_PARITY_FILAMENT_VARIANTS_REFERENCE=1 \
  ARES_PARITY_LIGHTNING_REFERENCE=1 ARES_PARITY_LOOP_CHAIN_REFERENCE=1 \
  ARES_PARITY_MULTIOBJECT_SKIRT_REFERENCE=1 ARES_PARITY_NORMAL_SUPPORT_REFERENCE=1 \
  ARES_PARITY_OBJECT_ID_REFERENCE=1 ARES_PARITY_OVERHANG_INTERSECTION_REFERENCE=1 \
  ARES_PARITY_REGION_FILAMENT_REFERENCE=1 ARES_PARITY_REGION_PERIMETERS_REFERENCE=1 \
  ARES_PARITY_SHORT_LINE_REFERENCE=1 ARES_PARITY_STITCH_JUNCTION_REFERENCE=1 \
  ARES_PARITY_SUPPORT_ANGLE_REFERENCE=1 ARES_PARITY_SUPPORT_ANNOTATIONS_REFERENCE=1 \
  ARES_PARITY_SUPPORT_FLOW_REFERENCE=1 ARES_PARITY_SUPPORT_MODIFIER_REFERENCE=1 \
  ARES_PARITY_SUPPORT_STYLE_REFERENCE=1 ARES_PARITY_TRANSITION_SNAP_REFERENCE=1 \
  ARES_PARITY_TREE_CONTAINMENT_REFERENCE=1 ARES_PARITY_TREE_SUPPORT_REFERENCE=1 \
  ARES_PARITY_VOLUME_OFFSETS_REFERENCE=1 ARES_PARITY_OVERRIDE_REFERENCE=1 \
  cargo llvm-cov -p ares-cli --test orca_parity --test stock_project_whole_file \
    --no-report
